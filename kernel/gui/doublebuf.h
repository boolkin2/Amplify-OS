// ============================================================================
// doublebuf.h - Двойная буферизация для MyOS
// ============================================================================
// Двойная буферизация предотвращает мерцание экрана:
//   1. Все операции рисования выполняются в back-буфер (в оперативной памяти)
//   2. После завершения кадра содержимое back-буфера копируется во фреймбуфер
//   3. Это делает обновление экрана мгновенным (одна быстрая операция memcpy)
// ============================================================================

#ifndef DOUBLEBUF_H
#define DOUBLEBUF_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// Функции двойной буферизации
// ============================================================================

// Инициализация двойного буфера
// Выделяет back-буфер в куче ядра размером = фреймбуфер
// Возвращает true при успехе
bool doublebuf_init(void);

// Проверка инициализации
bool doublebuf_is_initialized(void);

// Получение указателя на back-буфер (для прямого доступа)
uint32_t* doublebuf_get_buffer(void);

// Установка пикселя в back-буфер
void doublebuf_put_pixel(uint32_t x, uint32_t y, uint32_t color);

// Очистка back-буфера заданным цветом
void doublebuf_clear(uint32_t color);

// Копирование back-буфера во фреймбуфер (вывод на экран)
// Эта операция делает нарисованный кадр видимым
void doublebuf_swap(void);

// ----------------------------------------------------------------------------
// Scene-cache API (Этап 22+): базовый кадр без курсора, чтобы при движении
// мыши не нужно было перекомпозировать всю сцену.
// ----------------------------------------------------------------------------

// Сохранить текущий compose-буфер как «готовую сцену» (без курсора).
// Вызывается WM после полной перерисовки рабочего стола и окон.
void doublebuf_save_scene(void);

// Быстро скопировать кэш сцены обратно в compose-буфер, чтобы поверх неё
// добавить только курсор. Работает как один memcpy.
void doublebuf_restore_scene(void);

// Быстрая презентация: блит scene_buf → framebuffer напрямую (без
// compose-буфера). Используется для курсор-only обновлений — позволяет
// обойтись ОДНИМ memcpy вместо двух.
void doublebuf_present_scene(void);

// Проверить, есть ли сохранённая сцена.
bool doublebuf_has_scene(void);

#endif // DOUBLEBUF_H
