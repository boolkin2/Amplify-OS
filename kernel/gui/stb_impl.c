// ----------------------------------------------------------------------------
// stb_truetype — рендеринг TrueType-шрифтов (.ttf)
// ----------------------------------------------------------------------------
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

// ----------------------------------------------------------------------------
// stb_image — декодеры PNG и JPEG
// ----------------------------------------------------------------------------
#define STB_IMAGE_IMPLEMENTATION
#include "stb_image.h"
