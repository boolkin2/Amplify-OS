// ============================================================================
// font.h - Встроенный bitmap-шрифт 8x16 для MyOS
// ============================================================================
// Шрифт на основе CP437 (кодовая страница IBM PC)
// Каждый символ — 8 пикселей шириной, 16 пикселей высотой
// Один символ = 16 байт (каждый байт — одна строка, старший бит слева)
// ============================================================================

#ifndef FONT_H
#define FONT_H

#include <stdint.h>

// ============================================================================
// Константы шрифта
// ============================================================================

#define FONT_WIDTH      8       // Ширина глифа в пикселях
#define FONT_HEIGHT     16      // Высота глифа в пикселях
#define FONT_GLYPHS     256     // Количество символов в шрифте

// ============================================================================
// Данные шрифта
// ============================================================================

// Массив данных шрифта: 256 символов × 16 байт на символ = 4096 байт
extern const uint8_t font_8x16[FONT_GLYPHS * FONT_HEIGHT];

// ============================================================================
// Функции рендеринга текста
// ============================================================================

// Отрисовка одного символа в графическом режиме
// Параметры:
//   x, y  — позиция верхнего левого угла символа
//   c     — ASCII символ для отрисовки
//   fg    — цвет текста (0x00RRGGBB)
//   bg    — цвет фона (0x00RRGGBB), используйте 0xFF000000 для прозрачного
void font_draw_char(int32_t x, int32_t y, char c, uint32_t fg, uint32_t bg);

// Отрисовка строки текста
// Параметры:
//   x, y  — позиция верхнего левого угла первого символа
//   str   — нуль-терминированная строка
//   fg    — цвет текста
//   bg    — цвет фона (0xFF000000 для прозрачного)
void font_draw_string(int32_t x, int32_t y, const char* str, uint32_t fg, uint32_t bg);

// Отрисовка числа в десятичном формате
void font_draw_dec(int32_t x, int32_t y, int32_t num, uint32_t fg, uint32_t bg);

// Отрисовка числа в шестнадцатеричном формате
void font_draw_hex(int32_t x, int32_t y, uint32_t num, uint32_t fg, uint32_t bg);

// Получение ширины строки в пикселях
int32_t font_string_width(const char* str);

// Получение высоты строки в пикселях
int32_t font_string_height(void);

#endif // FONT_H
