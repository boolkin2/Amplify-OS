// ============================================================================
// wm.h - Оконный менеджер (Window Manager) для MyOS
// ============================================================================
// Управляет списком окон (Z-order), событиями мыши (перетаскивание, фокус)
// и финальным композитингом кадра.
// ============================================================================

#ifndef WM_H
#define WM_H

#include "window.h"

// Инициализация оконного менеджера
void wm_init(void);

// Добавление окна на экран (окно становится активным)
void wm_add_window(window_t* win);

// Удаление окна с экрана
void wm_remove_window(window_t* win);

// Принудительный запрос полной перерисовки сцены (окна двигались, контент
// окна изменился, desktop переконфигурирован и т.п.) — дорого.
void wm_require_redraw(void);

// Запрос только презентации нового кадра (курсор переехал, но сцена та же).
// Дёшево: WM просто восстановит кэш сцены и дорисует курсор.
void wm_require_present(void);

// Главная функция композитора (вызывается в цикле ядра)
// Обрабатывает события мыши и перерисовывает экран при необходимости
void wm_update(void);

// Получить текущее активное окно (на переднем плане)
window_t* wm_get_focused_window(void);

// Получить количество открытых окон
int wm_get_window_count(void);

// Перебрать все открытые окна (z-order, от верхнего к нижнему). Возвращает
// связный список через поле next; передавайте NULL для первого вызова или
// предыдущий результат для последующих. Используется диспетчером задач,
// чтобы показать GUI-приложения, которые не являются отдельными task_t.
window_t* wm_iterate_windows(window_t* prev);

#endif // WM_H
