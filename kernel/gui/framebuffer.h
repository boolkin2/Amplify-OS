// ============================================================================
// framebuffer.h - Управление линейным фреймбуфером VESA для MyOS
// ============================================================================
// Фреймбуфер — это область памяти, каждый пиксель которой напрямую
// отображается на экране. Формат пикселя: 32 бита (BGRX / 0xXXRRGGBB)
// ============================================================================

#ifndef FRAMEBUFFER_H
#define FRAMEBUFFER_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// Константы
// ============================================================================

// Желаемое разрешение (запрашиваем через Multiboot)
#define FB_DEFAULT_WIDTH    1024
#define FB_DEFAULT_HEIGHT   768
#define FB_DEFAULT_BPP      32      // Бит на пиксель

// ============================================================================
// Структура фреймбуфера
// ============================================================================

typedef struct {
    uint32_t* address;          // Указатель на начало видеопамяти
    uint32_t  width;            // Ширина экрана в пикселях
    uint32_t  height;           // Высота экрана в пикселях
    uint32_t  pitch;            // Количество байт в одной строке (может быть > width*4)
    uint32_t  bpp;              // Бит на пиксель (ожидаем 32)
    uint32_t  size;             // Общий размер фреймбуфера в байтах
    bool      initialized;     // Флаг успешной инициализации
} framebuffer_t;

// ============================================================================
// Функции фреймбуфера
// ============================================================================

// Инициализация фреймбуфера из данных Multiboot
// Параметры:
//   fb_addr   — физический адрес фреймбуфера (из Multiboot info)
//   fb_width  — ширина в пикселях
//   fb_height — высота в пикселях
//   fb_pitch  — байт на строку
//   fb_bpp    — бит на пиксель
// Возвращает true при успехе
bool framebuffer_init(uint32_t fb_addr, uint32_t fb_width, uint32_t fb_height,
                      uint32_t fb_pitch, uint32_t fb_bpp);

// Получение указателя на структуру фреймбуфера
framebuffer_t* framebuffer_get(void);

// Получение ширины экрана
uint32_t framebuffer_get_width(void);

// Получение высоты экрана
uint32_t framebuffer_get_height(void);

// Получение pitch (байт на строку)
uint32_t framebuffer_get_pitch(void);

// Проверка инициализации
bool framebuffer_is_initialized(void);

// Установка пикселя напрямую во фреймбуфер (без двойной буферизации)
// Параметры:
//   x, y  — координаты пикселя
//   color — цвет в формате 0x00RRGGBB
void framebuffer_put_pixel(uint32_t x, uint32_t y, uint32_t color);

// Очистка экрана заданным цветом
void framebuffer_clear(uint32_t color);

#endif // FRAMEBUFFER_H
