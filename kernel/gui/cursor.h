// ============================================================================
// cursor.h - Графический курсор мыши для MyOS
// ============================================================================
// Курсор рисуется напрямую во фреймбуфер для максимальной отзывчивости.
// При движении он восстанавливает фон из двойного буфера.
// ============================================================================

#ifndef CURSOR_H
#define CURSOR_H

#include <stdint.h>

// ============================================================================
// Функции курсора
// ============================================================================

// Инициализация курсора
void cursor_init(void);

// Обновление позиции курсора (вызывается из прерывания мыши)
// Автоматически восстанавливает фон и рисует курсор на новом месте
void cursor_update(int32_t x, int32_t y);

// Отрисовка курсора в compose-буфер (классический путь, перед swap).
void cursor_draw(void);

// Отрисовка курсора прямо во фреймбуфер (быстрый путь при
// doublebuf_present_scene — обходим лишний memcpy в compose).
void cursor_draw_to_framebuffer(void);

#endif // CURSOR_H
