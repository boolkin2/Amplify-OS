// ============================================================================
// image.h - Загрузка и отображение PNG/JPEG-изображений в MyOS (Этап 21)
// ============================================================================
// Использует stb_image для декодирования PNG и JPEG из памяти.
// Результат: 32-битное ARGB изображение в куче ядра.
// ============================================================================

#ifndef IMAGE_H
#define IMAGE_H

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

// ============================================================================
// Структура изображения в памяти
// ============================================================================
// pixels хранит RGBA (8 бит на канал). Размер буфера = width*height*4.

typedef struct {
    int32_t   width;       // Ширина в пикселях
    int32_t   height;      // Высота в пикселях
    uint8_t*  pixels;      // RGBA-байты, row-major
} image_t;

// ============================================================================
// Загрузка / освобождение
// ============================================================================

// Декодирует PNG или JPEG из буфера в памяти.
// Возвращает image_t* или NULL при ошибке.
image_t* image_load_from_memory(const uint8_t* data, size_t size);

// Загружает изображение из VFS по пути.
image_t* image_load(const char* path);

// Освобождает image_t и пиксели.
void image_free(image_t* img);

// ============================================================================
// Отрисовка
// ============================================================================

// Непрозрачная отрисовка (альфа-канал игнорируется).
// x, y — верхний левый угол на экране.
void image_draw(const image_t* img, int32_t x, int32_t y);

// Отрисовка с учётом альфа-канала (смешивание с фоном).
void image_draw_alpha(const image_t* img, int32_t x, int32_t y);

// Масштабирование методом ближайшего соседа (nearest neighbour).
// dst_w, dst_h — размеры на экране.
void image_draw_scaled(const image_t* img, int32_t x, int32_t y,
                       int32_t dst_w, int32_t dst_h);

#endif // IMAGE_H
