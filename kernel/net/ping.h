// ============================================================================
// ping.h — высокоуровневое API для пинга (Этап 34)
// ----------------------------------------------------------------------------
// Простая обёртка вокруг icmp_send_echo + icmp_set_reply_cb.
// Блокирующий ping_one() отправляет один Echo Request и ждёт Reply
// с таймаутом. Возвращает RTT в мс или -1 при потере.
// ============================================================================

#ifndef NET_PING_H
#define NET_PING_H

#include <stdint.h>

#define PING_TIMEOUT_MS  2000

// Возвращает RTT в мс (0..PING_TIMEOUT_MS) или -1 при таймауте.
// dst_ip — host-byte-order, seq — произвольный.
int ping_one(uint32_t dst_ip, uint16_t seq);

#endif // NET_PING_H
