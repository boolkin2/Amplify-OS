// ============================================================================
// dns.h — простой DNS-резолвер (Этап 34)
// ----------------------------------------------------------------------------
// Решает имя домена в IPv4-адрес через UDP/53.
// Сервер: gateway интерфейса (или 8.8.8.8 как fallback).
// Только A-запросы, без AAAA, без рекурсивных fallback'ов, без кеша TTL —
// простой кеш на N последних имён без истечения.
//
// API:
//   dns_resolve(name) — блокирующий запрос. Возвращает IPv4 (host-byte-order)
//   или 0, если не удалось разрешить за DNS_TIMEOUT_MS.
// ============================================================================

#ifndef NET_DNS_H
#define NET_DNS_H

#include <stdint.h>
#include <stdbool.h>

#define DNS_TIMEOUT_MS  3000

// Один раз — bind на UDP-порт.
void dns_init(void);

// Разрешить имя в IPv4. Возвращает 0 при ошибке/таймауте.
// Если name — уже A.B.C.D, парсит как литерал.
uint32_t dns_resolve(const char* name);

// Установить DNS-сервер вручную (host-byte-order). 0 = использовать gateway.
void dns_set_server(uint32_t srv_ip);

#endif // NET_DNS_H
