// ============================================================================
// initrd.h - Initial RAM Disk (InitRD) для MyOS
// ============================================================================
// InitRD — начальный RAM-диск, загружаемый GRUB как Multiboot модуль
// Содержит файлы, необходимые для работы ОС до монтирования реальной ФС
//
// Формат InitRD:
//   [initrd_header_t]               — заголовок (магическое число + кол-во файлов)
//   [initrd_file_header_t * N]      — массив заголовков файлов
//   [данные файла 1]                — содержимое первого файла
//   [данные файла 2]                — содержимое второго файла
//   ...
//   [данные файла N]                — содержимое последнего файла
// ============================================================================

#ifndef INITRD_H
#define INITRD_H

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include "vfs.h"

// ============================================================================
// Константы InitRD
// ============================================================================

// Магическое число для идентификации формата InitRD
#define INITRD_MAGIC            0x4D594F53  // "MYOS" в ASCII

// Максимальная длина имени файла в InitRD
#define INITRD_MAX_FILENAME     64

// Максимальное количество файлов в InitRD
// ВАЖНО: должно совпадать с константой в tools/mkinitrd.c
#define INITRD_MAX_FILES        256

// ============================================================================
// Структуры InitRD (формат на диске)
// ============================================================================

// Главный заголовок InitRD (расположен в начале образа)
typedef struct {
    uint32_t magic;             // Магическое число INITRD_MAGIC (0x4D594F53)
    uint32_t num_files;         // Количество файлов в образе
} __attribute__((packed)) initrd_header_t;

// Заголовок файла в InitRD (массив после главного заголовка)
typedef struct {
    char name[INITRD_MAX_FILENAME]; // Имя файла (с нулевым терминатором)
    uint32_t offset;            // Смещение данных файла от начала образа
    uint32_t size;              // Размер файла в байтах
} __attribute__((packed)) initrd_file_header_t;

// ============================================================================
// Информация об InitRD
// ============================================================================

typedef struct {
    bool loaded;                // Загружен ли InitRD
    uint32_t start_addr;        // Начальный адрес в памяти
    uint32_t end_addr;          // Конечный адрес в памяти
    uint32_t total_size;        // Общий размер образа
    uint32_t num_files;         // Количество файлов
} initrd_info_t;

// ============================================================================
// Функции InitRD
// ============================================================================

// Инициализация InitRD
// Параметры:
//   location — физический адрес начала образа InitRD в памяти
//              (передаётся из Multiboot module info)
// Возвращает указатель на корневой узел VFS (директория "/")
vfs_node_t* initrd_init(uint32_t location);

// Получение информации об InitRD
initrd_info_t initrd_get_info(void);

// Получение количества файлов в InitRD
uint32_t initrd_get_file_count(void);

// Получение имени файла по индексу
// Параметры:
//   index — индекс файла (0..num_files-1)
// Возвращает указатель на имя файла или NULL при ошибке
const char* initrd_get_filename(uint32_t index);

// Получение размера файла по индексу
// Параметры:
//   index — индекс файла (0..num_files-1)
// Возвращает размер файла или 0 при ошибке
uint32_t initrd_get_filesize(uint32_t index);

#endif // INITRD_H
