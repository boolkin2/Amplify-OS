// ============================================================================
// dynlink.h - Динамический линкер для MyOS (Этап 18)
// ============================================================================
// Реализует загрузку разделяемых библиотек и разрешение символов.
//
// Архитектура:
//   - Библиотеки (.so) загружаются в общую область памяти (0x50000000+)
//   - Каждая библиотека регистрирует свои экспортируемые символы
//   - При загрузке ELF-программы линкер разрешает внешние символы
//   - Используется упрощённая модель: прямой патч адресов (без GOT/PLT)
//
// Пример использования:
//   dynlink_init();
//   dynlink_load_library("libmyos.so", lib_data, lib_size);
//   uint32_t addr = dynlink_resolve("printf");
// ============================================================================

#ifndef DYNLINK_H
#define DYNLINK_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// Константы динамического линкера
// ============================================================================

// Максимальное количество загруженных библиотек
#define DYNLINK_MAX_LIBS        16

// Максимальное количество экспортируемых символов на библиотеку
#define DYNLINK_MAX_SYMBOLS     256

// Максимальное количество глобальных символов (все библиотеки)
#define DYNLINK_MAX_GLOBAL_SYMS 1024

// Максимальная длина имени символа
#define DYNLINK_MAX_SYM_NAME    64

// Максимальная длина имени библиотеки
#define DYNLINK_MAX_LIB_NAME    64

// Базовый адрес загрузки библиотек в userspace
// Библиотеки загружаются начиная с этого адреса
#define DYNLINK_LIB_BASE        0x50000000

// Шаг между библиотеками (1 MB на каждую)
#define DYNLINK_LIB_STEP        0x00100000

// ============================================================================
// Структуры динамического линкера
// ============================================================================

// Экспортируемый символ
typedef struct {
    char     name[DYNLINK_MAX_SYM_NAME];    // Имя символа (функции/переменной)
    uint32_t address;                        // Виртуальный адрес символа
    uint8_t  type;                           // Тип (STT_FUNC, STT_OBJECT)
    uint8_t  bind;                           // Привязка (STB_GLOBAL, STB_WEAK)
    bool     in_use;                         // Используется ли запись
} dynlink_symbol_t;

// Загруженная библиотека
typedef struct {
    char     name[DYNLINK_MAX_LIB_NAME];    // Имя библиотеки (напр. "libmyos.so")
    uint32_t base_addr;                      // Базовый адрес загрузки
    uint32_t end_addr;                       // Конец занятой памяти
    uint32_t size;                           // Размер в памяти
    uint32_t ref_count;                      // Счётчик ссылок
    bool     loaded;                         // Загружена ли

    // Таблица символов библиотеки
    dynlink_symbol_t symbols[DYNLINK_MAX_SYMBOLS];
    uint32_t symbol_count;                   // Количество экспортируемых символов
} dynlink_lib_t;

// Информация о динамическом линкере
typedef struct {
    uint32_t loaded_libs;                    // Количество загруженных библиотек
    uint32_t total_symbols;                  // Общее количество символов
    uint32_t resolved_count;                 // Количество разрешённых символов
    uint32_t unresolved_count;               // Количество неразрешённых
    uint32_t next_load_addr;                 // Следующий адрес загрузки
} dynlink_info_t;

// ============================================================================
// Функции динамического линкера
// ============================================================================

// Инициализация динамического линкера
void dynlink_init(void);

// Загрузка библиотеки из памяти
// Параметры:
//   name — имя библиотеки (напр. "libmyos.so")
//   data — указатель на данные ELF-файла библиотеки
//   size — размер данных
// Возвращает true при успехе
bool dynlink_load_library(const char* name, const void* data, uint32_t size);

// Загрузка библиотеки из файла на диске (VFS)
// Параметры:
//   path — путь к файлу (напр. "/disk/nexus/lib/libmyos.so")
// Возвращает true при успехе
bool dynlink_load_library_from_file(const char* path);

// Выгрузка библиотеки
// Параметры:
//   name — имя библиотеки
// Возвращает true при успехе
bool dynlink_unload_library(const char* name);

// Разрешение символа по имени (поиск во всех библиотеках)
// Параметры:
//   name — имя символа (функции/переменной)
// Возвращает адрес символа или 0 если не найден
uint32_t dynlink_resolve(const char* name);

// Регистрация символа ядра (для экспорта в userspace)
// Используется для предоставления функций ядра через syscall-обёртки
// Параметры:
//   name    — имя символа
//   address — адрес символа
//   type    — тип (STT_FUNC или STT_OBJECT)
// Возвращает true при успехе
bool dynlink_register_kernel_symbol(const char* name, uint32_t address, uint8_t type);

// Применение релокаций к загруженному ELF
// Параметры:
//   elf_data  — указатель на оригинальные данные ELF
//   elf_size  — размер ELF файла
//   base_addr — базовый адрес загрузки
// Возвращает количество успешно применённых релокаций
uint32_t dynlink_relocate(const void* elf_data, uint32_t elf_size, uint32_t base_addr);

// Получение информации о загруженных библиотеках
dynlink_info_t dynlink_get_info(void);

// Поиск библиотеки по имени
// Возвращает указатель на структуру библиотеки или NULL
const dynlink_lib_t* dynlink_find_library(const char* name);

// Вывод информации о всех загруженных библиотеках (для отладки)
void dynlink_print_info(void);

// Вывод таблицы символов (для отладки)
void dynlink_print_symbols(const char* lib_name);

#endif // DYNLINK_H
