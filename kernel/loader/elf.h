// ============================================================================
// elf.h - Определения формата ELF32 для MyOS (Этап 18)
// ============================================================================
// Формат ELF (Executable and Linkable Format) — стандартный формат
// исполняемых файлов в Unix-подобных ОС.
//
// Структура ELF файла:
//   [ELF Header]
//   [Program Header Table]  — описывает сегменты для загрузки
//   [Section Header Table]  — описывает секции для линковки
//   [.text]                 — исполняемый код
//   [.data]                 — инициализированные данные
//   [.bss]                  — неинициализированные данные
//   [.rodata]               — данные только для чтения
//   [.symtab]               — таблица символов
//   [.strtab]               — таблица строк
//   [.dynsym]               — динамические символы
//   [.dynstr]               — строки динамических символов
//   [.rel.plt]              — релокации PLT
// ============================================================================

#ifndef ELF_H
#define ELF_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// Магические числа ELF
// ============================================================================

#define ELF_MAGIC_0     0x7F    // Первый байт магического числа
#define ELF_MAGIC_1     'E'     // Второй байт
#define ELF_MAGIC_2     'L'     // Третий байт
#define ELF_MAGIC_3     'F'     // Четвёртый байт

// Проверка магического числа в заголовке
#define ELF_CHECK_MAGIC(hdr) \
    ((hdr)->e_ident[0] == ELF_MAGIC_0 && \
     (hdr)->e_ident[1] == ELF_MAGIC_1 && \
     (hdr)->e_ident[2] == ELF_MAGIC_2 && \
     (hdr)->e_ident[3] == ELF_MAGIC_3)

// ============================================================================
// Индексы в массиве e_ident[]
// ============================================================================

#define EI_MAG0         0       // Магический байт 0 (0x7F)
#define EI_MAG1         1       // Магический байт 1 ('E')
#define EI_MAG2         2       // Магический байт 2 ('L')
#define EI_MAG3         3       // Магический байт 3 ('F')
#define EI_CLASS        4       // Класс файла (32/64 бит)
#define EI_DATA         5       // Порядок байтов (little/big endian)
#define EI_VERSION      6       // Версия ELF
#define EI_OSABI        7       // ОС/ABI идентификатор
#define EI_ABIVERSION   8       // Версия ABI
#define EI_PAD          9       // Начало заполнения нулями
#define EI_NIDENT       16      // Размер массива e_ident

// ============================================================================
// Значения для EI_CLASS (класс файла)
// ============================================================================

#define ELFCLASSNONE    0       // Недопустимый класс
#define ELFCLASS32      1       // 32-битный ELF (наш формат!)
#define ELFCLASS64      2       // 64-битный ELF

// ============================================================================
// Значения для EI_DATA (порядок байтов)
// ============================================================================

#define ELFDATANONE     0       // Недопустимый порядок
#define ELFDATA2LSB     1       // Little-endian (x86)
#define ELFDATA2MSB     2       // Big-endian

// ============================================================================
// Типы ELF файлов (e_type)
// ============================================================================

#define ET_NONE         0       // Нет типа
#define ET_REL          1       // Релоцируемый файл (.o)
#define ET_EXEC         2       // Исполняемый файл
#define ET_DYN          3       // Разделяемый объект (.so)
#define ET_CORE         4       // Core dump

// ============================================================================
// Типы архитектур (e_machine)
// ============================================================================

#define EM_NONE         0       // Нет архитектуры
#define EM_386          3       // Intel 80386 (наша архитектура!)
#define EM_ARM          40      // ARM
#define EM_X86_64       62      // AMD x86-64

// ============================================================================
// Типы программных заголовков (p_type)
// ============================================================================

#define PT_NULL         0       // Неиспользуемый заголовок
#define PT_LOAD         1       // Загружаемый сегмент (главный!)
#define PT_DYNAMIC      2       // Информация для динамической линковки
#define PT_INTERP       3       // Путь к интерпретатору
#define PT_NOTE         4       // Вспомогательная информация
#define PT_SHLIB        5       // Зарезервировано
#define PT_PHDR         6       // Заголовок таблицы программных заголовков

// ============================================================================
// Флаги программных заголовков (p_flags)
// ============================================================================

#define PF_X            0x01    // Исполняемый сегмент
#define PF_W            0x02    // Записываемый сегмент
#define PF_R            0x04    // Читаемый сегмент

// ============================================================================
// Типы секций (sh_type)
// ============================================================================

#define SHT_NULL        0       // Неактивная секция
#define SHT_PROGBITS    1       // Данные программы (.text, .data, .rodata)
#define SHT_SYMTAB      2       // Таблица символов
#define SHT_STRTAB      3       // Таблица строк
#define SHT_RELA        4       // Релокации с добавлением (Rela)
#define SHT_HASH        5       // Хэш-таблица символов
#define SHT_DYNAMIC     6       // Информация динамической линковки
#define SHT_NOTE        7       // Примечания
#define SHT_NOBITS      8       // BSS (не занимает места в файле)
#define SHT_REL         9       // Релокации без добавления (Rel)
#define SHT_SHLIB       10      // Зарезервировано
#define SHT_DYNSYM      11      // Динамическая таблица символов

// ============================================================================
// Типы символов (ELF32_ST_TYPE)
// ============================================================================

#define STT_NOTYPE      0       // Тип не определён
#define STT_OBJECT      1       // Объект данных (переменная)
#define STT_FUNC        2       // Функция
#define STT_SECTION     3       // Секция
#define STT_FILE        4       // Имя исходного файла

// ============================================================================
// Привязка символов (ELF32_ST_BIND)
// ============================================================================

#define STB_LOCAL       0       // Локальный символ
#define STB_GLOBAL      1       // Глобальный символ
#define STB_WEAK        2       // Слабый символ

// ============================================================================
// Макросы для работы с символами
// ============================================================================

#define ELF32_ST_BIND(info)     ((info) >> 4)
#define ELF32_ST_TYPE(info)     ((info) & 0x0F)
#define ELF32_ST_INFO(bind, type) (((bind) << 4) | ((type) & 0x0F))

// ============================================================================
// Типы релокаций для i386
// ============================================================================

#define R_386_NONE      0       // Нет релокации
#define R_386_32        1       // Прямая 32-битная (S + A)
#define R_386_PC32      2       // Относительная (S + A - P)
#define R_386_GOT32     3       // GOT offset
#define R_386_PLT32     4       // PLT offset
#define R_386_GLOB_DAT  6       // GOT entry (S)
#define R_386_JMP_SLOT  7       // PLT entry (S)
#define R_386_RELATIVE  8       // Base + A

// Макросы для релокаций
#define ELF32_R_SYM(info)       ((info) >> 8)
#define ELF32_R_TYPE(info)      ((uint8_t)(info))

// ============================================================================
// Специальные индексы секций
// ============================================================================

#define SHN_UNDEF       0       // Неопределённая секция
#define SHN_ABS         0xFFF1  // Абсолютный символ

// ============================================================================
// Структуры ELF32
// ============================================================================

// Заголовок ELF файла (52 байта для ELF32)
typedef struct {
    uint8_t  e_ident[EI_NIDENT]; // Идентификация ELF (магические байты + класс)
    uint16_t e_type;             // Тип файла (ET_EXEC, ET_DYN и т.д.)
    uint16_t e_machine;          // Архитектура (EM_386 для x86)
    uint32_t e_version;          // Версия ELF (1 = текущая)
    uint32_t e_entry;            // Точка входа (виртуальный адрес _start)
    uint32_t e_phoff;            // Смещение таблицы программных заголовков
    uint32_t e_shoff;            // Смещение таблицы заголовков секций
    uint32_t e_flags;            // Флаги процессора
    uint16_t e_ehsize;           // Размер этого заголовка
    uint16_t e_phentsize;        // Размер одного программного заголовка
    uint16_t e_phnum;            // Количество программных заголовков
    uint16_t e_shentsize;        // Размер одного заголовка секции
    uint16_t e_shnum;            // Количество заголовков секций
    uint16_t e_shstrndx;         // Индекс секции строк заголовков секций
} __attribute__((packed)) elf32_header_t;

// Программный заголовок (описывает сегмент для загрузки)
typedef struct {
    uint32_t p_type;             // Тип сегмента (PT_LOAD и т.д.)
    uint32_t p_offset;           // Смещение сегмента в файле
    uint32_t p_vaddr;            // Виртуальный адрес загрузки
    uint32_t p_paddr;            // Физический адрес (обычно = p_vaddr)
    uint32_t p_filesz;           // Размер сегмента в файле
    uint32_t p_memsz;            // Размер сегмента в памяти (>= p_filesz для BSS)
    uint32_t p_flags;            // Флаги (PF_R, PF_W, PF_X)
    uint32_t p_align;            // Выравнивание сегмента
} __attribute__((packed)) elf32_phdr_t;

// Заголовок секции
typedef struct {
    uint32_t sh_name;            // Индекс имени в таблице строк
    uint32_t sh_type;            // Тип секции (SHT_PROGBITS и т.д.)
    uint32_t sh_flags;           // Флаги секции
    uint32_t sh_addr;            // Виртуальный адрес в памяти
    uint32_t sh_offset;          // Смещение в файле
    uint32_t sh_size;            // Размер секции
    uint32_t sh_link;            // Связанная секция (зависит от типа)
    uint32_t sh_info;            // Дополнительная информация
    uint32_t sh_addralign;       // Выравнивание
    uint32_t sh_entsize;         // Размер записи (для таблиц)
} __attribute__((packed)) elf32_shdr_t;

// Запись таблицы символов
typedef struct {
    uint32_t st_name;            // Индекс имени в таблице строк
    uint32_t st_value;           // Значение символа (адрес)
    uint32_t st_size;            // Размер символа
    uint8_t  st_info;            // Тип и привязка (ELF32_ST_TYPE/BIND)
    uint8_t  st_other;           // Видимость (обычно 0)
    uint16_t st_shndx;           // Индекс секции, в которой определён символ
} __attribute__((packed)) elf32_sym_t;

// Запись релокации (без добавления)
typedef struct {
    uint32_t r_offset;           // Адрес, который нужно изменить
    uint32_t r_info;             // Индекс символа + тип релокации
} __attribute__((packed)) elf32_rel_t;

// Запись релокации (с добавлением)
typedef struct {
    uint32_t r_offset;           // Адрес, который нужно изменить
    uint32_t r_info;             // Индекс символа + тип релокации
    int32_t  r_addend;           // Добавка к значению
} __attribute__((packed)) elf32_rela_t;

// Запись динамической секции
typedef struct {
    int32_t  d_tag;              // Тег (DT_NEEDED, DT_SYMTAB и т.д.)
    union {
        uint32_t d_val;          // Целочисленное значение
        uint32_t d_ptr;          // Адрес (указатель)
    } d_un;
} __attribute__((packed)) elf32_dyn_t;

// ============================================================================
// Теги динамической секции (d_tag)
// ============================================================================

#define DT_NULL         0       // Конец массива
#define DT_NEEDED       1       // Имя необходимой библиотеки
#define DT_PLTRELSZ     2       // Размер PLT релокаций
#define DT_HASH         4       // Хэш-таблица символов
#define DT_STRTAB       5       // Таблица строк
#define DT_SYMTAB       6       // Таблица символов
#define DT_RELA         7       // Таблица Rela релокаций
#define DT_RELASZ       8       // Размер Rela таблицы
#define DT_RELAENT      9       // Размер записи Rela
#define DT_STRSZ        10      // Размер таблицы строк
#define DT_SYMENT       11      // Размер записи символа
#define DT_REL          17      // Таблица Rel релокаций
#define DT_RELSZ        18      // Размер Rel таблицы
#define DT_RELENT       19      // Размер записи Rel
#define DT_PLTREL       20      // Тип PLT релокаций (DT_REL/DT_RELA)
#define DT_JMPREL       23      // Адрес PLT релокаций

// ============================================================================
// Результат загрузки ELF
// ============================================================================

// Максимальное количество загружаемых сегментов
#define ELF_MAX_SEGMENTS    16

// Информация о загруженном сегменте
typedef struct {
    uint32_t vaddr;             // Виртуальный адрес начала
    uint32_t memsz;             // Размер в памяти
    uint32_t flags;             // Флаги (PF_R, PF_W, PF_X)
} elf_segment_info_t;

// Результат загрузки ELF файла
typedef struct {
    bool     valid;             // Успешно ли загружен
    uint32_t entry_point;       // Точка входа (_start)
    uint32_t base_addr;         // Базовый адрес загрузки
    uint32_t end_addr;          // Конечный адрес (вершина занятой памяти)
    uint32_t segment_count;     // Количество загруженных сегментов
    elf_segment_info_t segments[ELF_MAX_SEGMENTS]; // Информация о сегментах
} elf_load_result_t;

// ============================================================================
// Функции ELF загрузчика
// ============================================================================

// Валидация ELF заголовка
// Проверяет магическое число, класс (32-bit), порядок байтов, архитектуру
// Параметры:
//   data — указатель на начало ELF файла в памяти
//   size — размер данных
// Возвращает true если заголовок валиден
bool elf_validate(const void* data, uint32_t size);

// Загрузка ELF файла в память процесса
// Парсит программные заголовки и загружает сегменты PT_LOAD
// Параметры:
//   data — указатель на начало ELF файла в памяти
//   size — размер данных
// Возвращает результат загрузки с точкой входа и информацией о сегментах
elf_load_result_t elf_load(const void* data, uint32_t size);

// Получение точки входа ELF файла без полной загрузки
// Параметры:
//   data — указатель на начало ELF файла
// Возвращает адрес точки входа или 0 при ошибке
uint32_t elf_get_entry(const void* data);

// Получение типа ELF файла
// Возвращает ET_EXEC, ET_DYN, ET_REL или 0 при ошибке
uint16_t elf_get_type(const void* data);

// Поиск секции по типу в ELF файле
// Параметры:
//   data      — указатель на ELF файл
//   sh_type   — тип секции (SHT_SYMTAB, SHT_STRTAB и т.д.)
// Возвращает указатель на заголовок секции или NULL
const elf32_shdr_t* elf_find_section(const void* data, uint32_t sh_type);

// Поиск секции по имени
// Параметры:
//   data — указатель на ELF файл
//   name — имя секции (например ".text", ".symtab")
// Возвращает указатель на заголовок секции или NULL
const elf32_shdr_t* elf_find_section_by_name(const void* data, const char* name);

// Поиск символа в ELF файле по имени
// Параметры:
//   data — указатель на ELF файл
//   name — имя символа
// Возвращает адрес символа или 0 если не найден
uint32_t elf_find_symbol(const void* data, const char* name);

// Вывод информации о ELF файле (для отладки)
void elf_print_info(const void* data);

#endif // ELF_H
