// ============================================================================
// shm.h — POSIX System V shared memory для MyOS (Стадия F)
// ============================================================================
// Упрощённая реализация:
//   - shmget(key, size, flags): создать или получить сегмент по ключу.
//     Возвращает id (>=0) или -1.
//   - shmat(id, NULL, 0): прикрепить сегмент к текущему vm; возвращает
//     виртуальный адрес в user-space, по которому доступен сегмент.
//   - shmdt(addr): отсоединить сегмент по адресу.
//   - shmctl(id, IPC_RMID, NULL): пометить сегмент к удалению; физические
//     страницы освобождаются, когда последний процесс отсоединяется.
//
// Ограничения текущей реализации:
//   - Общий адрес прикрепления выбирается автоматически из mmap-арены vm.
//   - Нет прав доступа, owner'а, очередей, статистики.
//   - IPC_PRIVATE (key=0) тоже поддерживается: каждый вызов создаёт новый.
// ============================================================================

#ifndef SHM_H
#define SHM_H

#include <stdint.h>

// Флаги shmget
#define SHM_IPC_CREAT   0x200    // Создать если не существует
#define SHM_IPC_EXCL    0x400    // С IPC_CREAT — падать, если уже есть
#define SHM_IPC_PRIVATE 0        // Особый key для анонимного сегмента

// Команды shmctl
#define SHM_IPC_RMID    0        // Удалить сегмент

// Инициализация подсистемы (однажды при старте ядра).
void shm_init(void);

// API системных вызовов
int      shm_get(int key, uint32_t size, int flags);
uint32_t shm_attach(int id);
int      shm_detach(uint32_t vaddr);
int      shm_ctl(int id, int cmd);

#endif // SHM_H
