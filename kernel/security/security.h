// ============================================================================
// security.h - Подсистема безопасности и многопользовательности (Этап 32)
// ============================================================================
// Реализует:
//   1) Базу пользователей с хешированием паролей и солью.
//   2) Хранение БД на FAT32 диске в /disk/Sanctum/users.db (если ФС доступна),
//      либо в RAM (fallback) для headless-режимов.
//   3) Полноэкранный мастер первого запуска (Welcome / Create Admin) — если
//      БД пуста.
//   4) Полноэкранный экран входа (Login Screen) — если БД содержит хотя бы
//      одного пользователя.
//   5) Активную сессию (uid/gid/имя), используемую VFS для проверки RWX-прав.
//   6) Хук в обработчик исключений CPU: процесс Ring 3 при крахе помечается
//      DEAD, а ядро продолжает работать.
//
// Точка входа: security_run() — вызывается из kernel_main() ПОСЛЕ
// инициализации WM/desktop, но ДО основного цикла обновления экрана.
// Функция блокирует поток ядра до тех пор, пока пользователь не пройдёт
// аутентификацию.
// ============================================================================

#ifndef SECURITY_H
#define SECURITY_H

#include <stdint.h>
#include <stdbool.h>

// ----------------------------------------------------------------------------
// Лимиты
// ----------------------------------------------------------------------------

// Максимальное число пользователей в системе.
#define SEC_MAX_USERS           16

// Максимальная длина имени пользователя (без \0).
#define SEC_USERNAME_MAX        31

// Максимальная длина «полного имени» (Display Name, без \0).
#define SEC_DISPLAYNAME_MAX     63

// Максимальная длина пароля при вводе (без \0). В БД пароль не хранится —
// там лежит только хеш и соль.
#define SEC_PASSWORD_MAX        63

// Длина соли (байт). Соль генерируется детерминированно из времени и счётчика
// (генератора случайных чисел в ядре пока нет, см. sec_make_salt()).
#define SEC_SALT_LEN            16

// Длина хеша пароля (байт). Используется собственный кастомный хеш на базе
// FNV-1a + 4096 раундов перемешивания — этого достаточно для учебной ОС;
// при наличии Newlib/SHA это место можно безболезненно заменить.
#define SEC_HASH_LEN            32

// Специальные UID/GID.
#define SEC_UID_ROOT            0       // root — суперпользователь
#define SEC_GID_ROOT            0
#define SEC_GID_USERS           100     // группа обычных пользователей

// ----------------------------------------------------------------------------
// Маски прав доступа (Unix-style)
// ----------------------------------------------------------------------------

#define SEC_S_IRUSR             0400    // r для владельца
#define SEC_S_IWUSR             0200    // w для владельца
#define SEC_S_IXUSR             0100    // x для владельца
#define SEC_S_IRGRP             0040    // r для группы
#define SEC_S_IWGRP             0020    // w для группы
#define SEC_S_IXGRP             0010    // x для группы
#define SEC_S_IROTH             0004    // r для остальных
#define SEC_S_IWOTH             0002    // w для остальных
#define SEC_S_IXOTH             0001    // x для остальных

// Стандартные комбинации.
#define SEC_MODE_FILE_DEFAULT   0644    // rw-r--r--
#define SEC_MODE_DIR_DEFAULT    0755    // rwxr-xr-x
#define SEC_MODE_FILE_PRIVATE   0600    // rw-------
#define SEC_MODE_FILE_SYSTEM    0644    // rw-r--r--

// Что именно проверяем при доступе.
typedef enum {
    SEC_PERM_READ  = 0x4,
    SEC_PERM_WRITE = 0x2,
    SEC_PERM_EXEC  = 0x1
} sec_perm_t;

// ----------------------------------------------------------------------------
// Запись в БД пользователей (на диске лежит как массив этих структур,
// little-endian, выравнивание 4 байта)
// ----------------------------------------------------------------------------

typedef struct {
    uint32_t magic;                            // 'AOSU' (0x554F4F41)
    uint32_t uid;                              // UID
    uint32_t gid;                              // GID
    uint32_t flags;                            // битовые флаги (admin/disabled/...)
    char     name[SEC_USERNAME_MAX + 1];       // login (\0-terminated)
    char     display[SEC_DISPLAYNAME_MAX + 1]; // отображаемое имя
    uint8_t  salt[SEC_SALT_LEN];               // случайная соль
    uint8_t  hash[SEC_HASH_LEN];               // хеш(пароль || соль)
} sec_user_t;

// Флаги пользователя.
#define SEC_UFLAG_ADMIN     0x0001          // администратор (uid==0 ИЛИ этот флаг)
#define SEC_UFLAG_DISABLED  0x0002          // запись отключена

// ----------------------------------------------------------------------------
// БД пользователей: заголовок файла на диске
// ----------------------------------------------------------------------------

#define SEC_DB_MAGIC        0x42445541      // 'AUDB'  (Amplify Users DB)
#define SEC_DB_VERSION      1

typedef struct {
    uint32_t magic;         // SEC_DB_MAGIC
    uint32_t version;       // SEC_DB_VERSION
    uint32_t user_count;    // сколько пользователей хранится
    uint32_t reserved;      // выравнивание
} sec_db_header_t;

// ----------------------------------------------------------------------------
// Активная сессия
// ----------------------------------------------------------------------------

typedef struct {
    bool     active;
    uint32_t uid;
    uint32_t gid;
    bool     is_admin;
    char     name[SEC_USERNAME_MAX + 1];
    char     display[SEC_DISPLAYNAME_MAX + 1];
} sec_session_t;

// ============================================================================
// Публичный API
// ============================================================================

// Главная точка входа Этапа 32. Вызывается из kernel_main() после desktop_init.
// Делает следующее:
//   1) Инициализирует БД (читает /disk/Sanctum/users.db; если файла нет —
//      готовит пустую БД в памяти).
//   2) Если БД пуста — запускает first-boot wizard (Welcome + Create Admin),
//      сохраняет нового admin'а на диск.
//   3) Запускает Login Screen, ждёт корректного ввода пароля.
//   4) Заполняет активную сессию sec_get_session() — после возврата из этой
//      функции остальная ОС может проверять права.
// Никогда не возвращает управление до успешной аутентификации.
void security_run(void);

// Доступна ли ФС, куда можно сохранять БД? (mount /disk/...)
// При false БД остаётся только в RAM, и при перезапуске мастер будет повторён.
bool security_disk_available(void);

// ----------------------------------------------------------------------------
// API БД пользователей (users.c)
// ----------------------------------------------------------------------------

void sec_users_init(void);
int  sec_users_count(void);
const sec_user_t* sec_users_get(int index);
const sec_user_t* sec_users_find_by_name(const char* name);
const sec_user_t* sec_users_find_by_uid(uint32_t uid);

// Проверка пароля. Возвращает указатель на запись пользователя, если пароль
// верный. Иначе NULL. Безопасно сравнивает хеши в постоянное время.
const sec_user_t* sec_users_authenticate(const char* name, const char* password);

// Создать нового пользователя (генерирует соль, хеширует пароль).
// Возвращает 0 при успехе, отрицательный код ошибки при провале
// (имя занято / БД переполнена / не сохранилось на диск).
int sec_users_create(const char* name, const char* display,
                     const char* password, bool is_admin);

// Сохранить БД на диск (если /disk доступен). Возвращает 0 при успехе.
int sec_users_save(void);

// Загрузить БД с диска. Возвращает 0 при успехе, -1 если файла нет
// (тогда БД пустая → нужен first-boot wizard).
int sec_users_load(void);

// ----------------------------------------------------------------------------
// API проверки прав (perms.c)
// ----------------------------------------------------------------------------

// Проверка прав доступа: совместима с Unix-семантикой.
// Возвращает true, если у пользователя (uid, gid) есть запрошенное право
// (any of SEC_PERM_*). root всегда получает true.
bool sec_check_perm(uint32_t file_uid, uint32_t file_gid, uint32_t mode,
                    uint32_t actor_uid, uint32_t actor_gid, sec_perm_t perm);

// Удобный wrapper, использующий текущую сессию.
bool sec_check_perm_current(uint32_t file_uid, uint32_t file_gid,
                            uint32_t mode, sec_perm_t perm);

// ----------------------------------------------------------------------------
// API сессии (session.c — внутри security.c)
// ----------------------------------------------------------------------------

void sec_session_set(const sec_user_t* u);
void sec_session_clear(void);
const sec_session_t* sec_get_session(void);

// Выйти из учётной записи (Logout). После вызова security_run() покажет
// экран входа заново. Из shutdown'а вызывать не нужно.
void sec_logout(void);

// ----------------------------------------------------------------------------
// API хеширования (внутреннее, но экспонируется для тестов)
// ----------------------------------------------------------------------------

void sec_make_salt(uint8_t out[SEC_SALT_LEN]);
void sec_hash_password(const char* password, const uint8_t salt[SEC_SALT_LEN],
                       uint8_t out[SEC_HASH_LEN]);

// Сравнение в постоянное время (защита от timing-атак).
bool sec_const_time_eq(const void* a, const void* b, uint32_t len);

// ----------------------------------------------------------------------------
// API мастера первого запуска (firstboot.c)
// ----------------------------------------------------------------------------

// Показывает Welcome-экран с краткой презентацией ОС, затем форму создания
// администратора (имя, отображаемое имя, пароль ×2). По завершению создаёт
// пользователя в БД и сохраняет её на диск.
// Никогда не возвращает управление до успешного создания администратора.
void sec_firstboot_run(void);

// ----------------------------------------------------------------------------
// API экрана логина (login.c)
// ----------------------------------------------------------------------------

// Показывает список пользователей и поле ввода пароля. Возвращает указатель
// на пользователя, успешно прошедшего аутентификацию.
// Не возвращает управление до успешного логина.
const sec_user_t* sec_login_run(void);

// ----------------------------------------------------------------------------
// Хук Ring 3 isolation (вызывается из interrupt.c при exception в Ring 3)
// ----------------------------------------------------------------------------

// Вызывается из обработчика CPU-исключения, если оно произошло в Ring 3
// (CS.RPL == 3). Помечает текущий task DEAD, логирует крах в serial,
// освобождает CR3 и переключает планировщик. НЕ ВОЗВРАЩАЕТСЯ.
// Если current_task == NULL (мы ещё в init) — функция возвращает false и
// штатный обработчик уходит в halt.
bool sec_ring3_handle_fault(int int_no, uint32_t err_code,
                            uint32_t eip, uint32_t cr2);

#endif // SECURITY_H
