// ============================================================================
// vm.h — Адресное пространство (vm_space) для MyOS
// ============================================================================
// vm_space_t — обёртка над page_directory_t с подсчётом ссылок.
// Идея:
//   • Каждая задача (task_t) владеет указателем на vm_space_t*.
//   • Потоки в пределах одного «процесса» (SYS_CLONE) разделяют vm_space,
//     увеличивая refcount.
//   • fork() создаёт новое vm_space с копией таблиц (COW в стадии C).
//   • Когда последний поток завершается, refcount падает до 0 и мы
//     освобождаем все user-страницы + сам PD.
//   • Ядерные задачи (kernel threads) используют общее ядерное vm_space,
//     которое никогда не освобождается.
// ============================================================================

#ifndef VM_H
#define VM_H

#include <stdint.h>
#include "paging.h"

// Структура адресного пространства
typedef struct vm_space {
    page_directory_t* pd;   // Каталог страниц (физ. адрес совпадает с вирт. в identity-map)
    int refcount;           // Сколько задач используют это пространство
    uint32_t mmap_top;      // Текущая вершина mmap-арены (растёт вверх от USER_MMAP_BASE)
    int is_kernel;          // 1 для общего ядерного vm; не освобождается в release
} vm_space_t;

// Инициализация подсистемы. Оборачивает существующий kernel_page_directory
// в постоянное ядерное vm_space. Должна вызываться после paging_init().
void vm_init(void);

// Ядерное vm_space (общее для всех потоков ядра)
vm_space_t* vm_kernel(void);

// Создание нового пользовательского vm_space.
// Новый PD содержит копии ядерных PDE (identity-map + хардверные маппинги).
// refcount = 1, mmap_top = USER_MMAP_BASE.
// Возвращает NULL при OOM.
vm_space_t* vm_create_user(void);

// Клонирование родительского vm_space с Copy-On-Write для fork().
// Оба пространства делят физические страницы; при первой записи любой
// стороны #PF handler материализует приватную копию. Наследует mmap_top.
// refcount нового vm = 1. Возвращает NULL при OOM.
vm_space_t* vm_clone_cow(vm_space_t* parent);

// Увеличить refcount (для SYS_CLONE-потоков, делящих адресное пространство)
vm_space_t* vm_retain(vm_space_t* vm);

// Уменьшить refcount. Если стало 0 и vm не ядерное — освободить все
// пользовательские страницы, пользовательские page tables и сам PD.
// Принимает NULL без вреда (no-op).
void vm_release(vm_space_t* vm);

// Переключить активное адресное пространство.
// Загружает CR3 только если PD отличается от текущего.
// NULL трактуется как «переключиться на ядерное vm».
void vm_switch(vm_space_t* vm);

// Вернуть vm_space текущей задачи (то, на которое сейчас указывает CR3).
vm_space_t* vm_current(void);

#endif // VM_H
