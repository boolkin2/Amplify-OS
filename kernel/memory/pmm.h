// ============================================================================
// pmm.h - Physical Memory Manager для MyOS
// ============================================================================
// Управляет физической памятью через bitmap аллокатор
// Каждый бит в bitmap представляет одну страницу (4KB)
// ============================================================================

#ifndef PMM_H
#define PMM_H

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include "memory.h"

// ============================================================================
// Константы PMM
// ============================================================================

// Максимальный размер памяти для управления (512 MB)
#define PMM_MAX_MEMORY      (512 * MB)

// Количество страниц
#define PMM_MAX_PAGES       (PMM_MAX_MEMORY / PAGE_SIZE)

// Размер bitmap (в байтах)
#define PMM_BITMAP_SIZE     (PMM_MAX_PAGES / 8)

// ============================================================================
// Структуры PMM
// ============================================================================

// Информация о физической памяти
typedef struct {
    uint32_t total_memory;      // Общий объём памяти (байты)
    uint32_t used_memory;       // Использованная память (байты)
    uint32_t free_memory;       // Свободная память (байты)
    uint32_t total_pages;       // Общее количество страниц
    uint32_t used_pages;        // Использованные страницы
    uint32_t free_pages;        // Свободные страницы
} pmm_info_t;

// ============================================================================
// Функции PMM
// ============================================================================

// Инициализация Physical Memory Manager
// Параметры:
//   mem_size - размер доступной памяти в байтах
//   kernel_end - адрес конца ядра
void pmm_init(uint32_t mem_size, uint32_t kernel_end);

// Выделение одной физической страницы (4KB)
// Возвращает физический адрес страницы или 0 при ошибке
uint32_t pmm_alloc_page(void);

// Освобождение одной физической страницы
// Параметры:
//   page_addr - физический адрес страницы
void pmm_free_page(uint32_t page_addr);

// Выделение нескольких последовательных страниц
// Параметры:
//   count - количество страниц
// Возвращает физический адрес первой страницы или 0 при ошибке
uint32_t pmm_alloc_pages(uint32_t count);

// Освобождение нескольких последовательных страниц
// Параметры:
//   page_addr - физический адрес первой страницы
//   count - количество страниц
void pmm_free_pages(uint32_t page_addr, uint32_t count);

// Получение информации о памяти
pmm_info_t pmm_get_info(void);

// Проверка, свободна ли страница
// Параметры:
//   page_addr - физический адрес страницы
// Возвращает true если страница свободна
bool pmm_is_page_free(uint32_t page_addr);

// Резервирование области памяти (пометка как занятой)
// Используется для резервирования памяти ядра, видеопамяти и т.д.
// Параметры:
//   start_addr - начальный адрес
//   size - размер области в байтах
void pmm_reserve_region(uint32_t start_addr, uint32_t size);

// ============================================================================
// Подсчёт ссылок на физические страницы (нужен для Copy-On-Write)
// ============================================================================
//
// Каждая физическая страница имеет refcount (uint8_t). При pmm_alloc_page
// refcount ставится в 1. pmm_inc_ref(addr) инкрементирует; pmm_free_page
// декрементирует и действительно освобождает страницу только при refcount=0.
//
// При fork() родитель и ребёнок разделяют одни и те же физические страницы
// (каждая получает PTE с COW-флагом и отнятым W). fork вызывает inc_ref
// на каждую такую страницу. Когда одна из сторон делает запись и ловит
// #PF, обработчик смотрит refcount: если 1 — просто снимает COW/ставит W;
// если >1 — копирует содержимое в новую страницу и декрементирует старую.

// Увеличить счётчик ссылок на страницу (≥2 после fork). Никогда не вызывает
// реальное выделение; предполагает, что страница уже была выделена.
void pmm_inc_ref(uint32_t page_addr);

// Прочитать текущий refcount для диагностики и логики COW.
uint8_t pmm_get_ref(uint32_t page_addr);

#endif // PMM_H
