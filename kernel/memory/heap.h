// ============================================================================
// heap.h - Heap Allocator для MyOS (kmalloc/kfree)
// ============================================================================
// Простой аллокатор кучи для динамического выделения памяти
// Использует алгоритм First-Fit с заголовками блоков
// ============================================================================

#ifndef HEAP_H
#define HEAP_H

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include "memory.h"

// ============================================================================
// Константы Heap
// ============================================================================

// Начальный адрес кучи (после ядра)
#define HEAP_START          0x00400000  // 4 MB

// Размер кучи (24 MB) — хватает на framebuffer-буферы композитинга
// (3 MB × 2 = 6 MB) + рабочие алокации, приложения, scratch-память.
#define HEAP_SIZE           (24 * MB)

// Конечный адрес кучи
#define HEAP_END            (HEAP_START + HEAP_SIZE)

// Минимальный размер блока (включая заголовок)
#define HEAP_MIN_BLOCK_SIZE 32

// Магическое число для проверки целостности блока
#define HEAP_MAGIC          0xDEADBEEF

// ============================================================================
// Структуры Heap
// ============================================================================

// Заголовок блока памяти
typedef struct heap_block {
    uint32_t magic;             // Магическое число для проверки
    uint32_t size;              // Размер блока (без заголовка)
    bool is_free;               // Свободен ли блок
    struct heap_block* next;    // Следующий блок
    struct heap_block* prev;    // Предыдущий блок
} heap_block_t;

// Информация о куче
typedef struct {
    uint32_t total_size;        // Общий размер кучи
    uint32_t used_size;         // Использованная память
    uint32_t free_size;         // Свободная память
    uint32_t block_count;       // Количество блоков
    uint32_t free_blocks;       // Количество свободных блоков
    uint32_t used_blocks;       // Количество занятых блоков
} heap_info_t;

// ============================================================================
// Функции Heap
// ============================================================================

// Инициализация кучи
void heap_init(void);

// Выделение памяти (аналог malloc)
// Параметры:
//   size - размер в байтах
// Возвращает указатель на выделенную память или NULL при ошибке
void* kmalloc(size_t size);

// Освобождение памяти (аналог free)
// Параметры:
//   ptr - указатель на память, выделенную через kmalloc
void kfree(void* ptr);

// Выделение памяти с выравниванием
// Параметры:
//   size - размер в байтах
//   align - выравнивание (должно быть степенью 2)
// Возвращает указатель на выделенную память или NULL при ошибке
void* kmalloc_aligned(size_t size, size_t align);

// Выделение и обнуление памяти (аналог calloc)
// Параметры:
//   num - количество элементов
//   size - размер одного элемента
// Возвращает указатель на выделенную память или NULL при ошибке
void* kcalloc(size_t num, size_t size);

// Изменение размера выделенной памяти (аналог realloc)
// Параметры:
//   ptr - указатель на память, выделенную через kmalloc
//   new_size - новый размер
// Возвращает указатель на память (может быть другим адресом) или NULL при ошибке
void* krealloc(void* ptr, size_t new_size);

// Получение информации о куче
heap_info_t heap_get_info(void);

// Проверка целостности кучи (для отладки)
bool heap_check_integrity(void);

#endif // HEAP_H
