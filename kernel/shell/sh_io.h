// ============================================================================
// sh_io.h — Абстракция ввода/вывода для shell (Этап 29)
// ----------------------------------------------------------------------------
// Контекст исполнения команды: куда направлять вывод и откуда брать вход.
// Если out_pipe == NULL — пишем напрямую в VGA. Если in_pipe == NULL — читаем
// с клавиатуры (для интерактивных команд) либо просто работаем без stdin.
//
// Эта абстракция позволяет команде, не зная заранее, выполняется ли она в
// одиночку или внутри конвейера (`cmd1 | cmd2`), писать одинаковыми вызовами
// и попадать туда, куда укажет shell.
// ============================================================================

#ifndef SHELL_SH_IO_H
#define SHELL_SH_IO_H

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

#include "../ipc/pipe.h"
#include "../vga.h"

typedef struct sh_ctx {
    pipe_t* out_pipe;   // куда пишем (NULL → VGA)
    pipe_t* in_pipe;    // откуда читаем (NULL → нет stdin / клавиатура)
    int     pid;        // pid команды в таблице сигналов (или 0 если без)
} sh_ctx_t;

// Установить «активный» контекст для текущей команды. Команды используют
// глобальный контекст вместо явной передачи параметром, чтобы не переписывать
// сигнатуры всех старых обработчиков.
void    sh_ctx_set(sh_ctx_t* ctx);
sh_ctx_t* sh_ctx_get(void);

// ---------- ВЫВОД ----------
// Все эти функции уважают активный контекст: пишут либо в pipe (без цветов
// и форматирования), либо в VGA (с цветами).

void sh_putc(char c);
void sh_puts(const char* s);
void sh_println(const char* s);
void sh_print_dec(uint32_t n);

// Цвет работает только в режиме VGA. В pipe-режиме игнорируется.
void sh_set_color(vga_color_t fg, vga_color_t bg);

// ---------- ВВОД ----------
// Прочитать одну строку из in_pipe (без \n). Возвращает количество прочитанных
// байт или -1 если pipe пуст и закрыт (EOF), или 0 если pipe пуст, но не закрыт.
// Если in_pipe == NULL → возвращает -1 сразу (нет stdin).
int sh_readline_pipe(char* buf, int max_len);

// Удобный helper: построчная итерация по in_pipe.
// out_buf должен иметь capacity >= max_len байт.
// Возвращает true если строка получена; false если EOF.
bool sh_next_line(char* out_buf, int max_len);

#endif // SHELL_SH_IO_H
