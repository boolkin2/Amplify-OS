// ============================================================================
// shell.h - Командная оболочка MyOS
// ============================================================================
// Полноценный интерактивный shell с набором встроенных команд
// Поддерживает историю команд и цветной вывод
// ============================================================================

#ifndef SHELL_H
#define SHELL_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// Константы Shell
// ============================================================================

// Максимальная длина командной строки
#define SHELL_MAX_INPUT         256

// Максимальное количество аргументов команды
#define SHELL_MAX_ARGS          16

// Максимальная длина одного аргумента
#define SHELL_MAX_ARG_LEN       64

// Размер истории команд
#define SHELL_HISTORY_SIZE      16

// ============================================================================
// Функции Shell
// ============================================================================

// Запуск командной оболочки (бесконечный цикл)
void shell_run(void);

// Выполнение одной команды (используется и в shell_run, и в GUI терминале)
void shell_execute_command(char* input);

#endif // SHELL_H
