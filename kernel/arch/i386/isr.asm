; ============================================================================
; isr.asm - Обработчики исключений CPU (ISR 0-31)
; ============================================================================
; Interrupt Service Routines для исключений процессора
; Каждое исключение имеет свой обработчик, который сохраняет состояние
; регистров и вызывает общий обработчик на C
; ============================================================================

[BITS 32]

section .text

; Экспортируем обработчики для использования в C
global isr0, isr1, isr2, isr3, isr4, isr5, isr6, isr7
global isr8, isr9, isr10, isr11, isr12, isr13, isr14, isr15
global isr16, isr17, isr18, isr19, isr20, isr21, isr22, isr23
global isr24, isr25, isr26, isr27, isr28, isr29, isr30, isr31
global isr128

; Импортируем общий обработчик из C
extern isr_handler

; ============================================================================
; Макросы для создания обработчиков
; ============================================================================

; Макрос для исключений БЕЗ кода ошибки
; Процессор не помещает код ошибки в стек, поэтому мы добавляем 0
%macro ISR_NOERRCODE 1
isr%1:
    cli                             ; Отключаем прерывания
    push dword 0                    ; Фиктивный код ошибки (0)
    push dword %1                   ; Номер прерывания
    jmp isr_common_stub             ; Переход к общему обработчику
%endmacro

; Макрос для исключений С кодом ошибки
; Процессор уже поместил код ошибки в стек
%macro ISR_ERRCODE 1
isr%1:
    cli                             ; Отключаем прерывания
    push dword %1                   ; Номер прерывания
    jmp isr_common_stub             ; Переход к общему обработчику
%endmacro

; ============================================================================
; Определение обработчиков исключений (0-31)
; ============================================================================

; Исключения БЕЗ кода ошибки
ISR_NOERRCODE 0     ; 0: Деление на ноль
ISR_NOERRCODE 1     ; 1: Отладка
ISR_NOERRCODE 2     ; 2: Non-Maskable Interrupt
ISR_NOERRCODE 3     ; 3: Точка останова
ISR_NOERRCODE 4     ; 4: Переполнение
ISR_NOERRCODE 5     ; 5: Выход за границы
ISR_NOERRCODE 6     ; 6: Недопустимая инструкция
ISR_NOERRCODE 7     ; 7: Устройство недоступно

; Исключения С кодом ошибки
ISR_ERRCODE   8     ; 8: Двойная ошибка
ISR_NOERRCODE 9     ; 9: Сегмент сопроцессора (устарело)
ISR_ERRCODE   10    ; 10: Недопустимый TSS
ISR_ERRCODE   11    ; 11: Сегмент отсутствует
ISR_ERRCODE   12    ; 12: Ошибка сегмента стека
ISR_ERRCODE   13    ; 13: Общая защита
ISR_ERRCODE   14    ; 14: Ошибка страницы
ISR_NOERRCODE 15    ; 15: Зарезервировано

ISR_NOERRCODE 16    ; 16: Ошибка FPU
ISR_ERRCODE   17    ; 17: Проверка выравнивания
ISR_NOERRCODE 18    ; 18: Проверка машины
ISR_NOERRCODE 19    ; 19: SIMD исключение
ISR_NOERRCODE 20    ; 20: Виртуализация

; Зарезервированные (21-31)
ISR_NOERRCODE 21
ISR_NOERRCODE 22
ISR_NOERRCODE 23
ISR_NOERRCODE 24
ISR_NOERRCODE 25
ISR_NOERRCODE 26
ISR_NOERRCODE 27
ISR_NOERRCODE 28
ISR_NOERRCODE 29
ISR_NOERRCODE 30
ISR_NOERRCODE 31

; Системный вызов (Syscall)
ISR_NOERRCODE 128

; ============================================================================
; Общий обработчик прерываний
; ============================================================================
; Вызывается всеми ISR после сохранения номера прерывания и кода ошибки
; Сохраняет все регистры и вызывает обработчик на C

isr_common_stub:
    ; Сохраняем все регистры общего назначения
    pusha                           ; Сохраняет EAX, ECX, EDX, EBX, ESP, EBP, ESI, EDI

    ; Сохраняем сегментные регистры
    mov ax, ds                      ; Сохраняем DS
    push eax

    ; Загружаем сегмент данных ядра
    mov ax, 0x10                    ; 0x10 = селектор данных ядра
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax

    ; Вызываем обработчик на C
    ; Передаём указатель на структуру registers_t (ESP указывает на неё)
    push esp                        ; Передаём указатель на стек (registers_t*)
    call isr_handler                ; Вызов обработчика на C
    add esp, 4                      ; Очищаем параметр

    ; Восстанавливаем сегментные регистры
    pop eax                         ; Восстанавливаем DS
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax

    ; Восстанавливаем регистры общего назначения
    popa                            ; Восстанавливает EDI, ESI, EBP, ESP, EBX, EDX, ECX, EAX

    ; Очищаем код ошибки и номер прерывания
    add esp, 8                      ; Убираем int_no и err_code

    ; Включаем прерывания и возвращаемся
    sti                             ; Включить прерывания
    iret                            ; Возврат из прерывания (восстанавливает EIP, CS, EFLAGS)
