; ============================================================================
; boot.asm - Точка входа в ядро MyOS
; ============================================================================
; Этот файл содержит:
; 1. Multiboot header для загрузки через GRUB
;    (с запросом графического режима VESA 1024x768x32)
; 2. Начальную настройку стека
; 3. Передачу управления в kernel_main() на C
; ============================================================================

; Константы Multiboot
MULTIBOOT_MAGIC         equ 0x1BADB002          ; Магическое число Multiboot
MULTIBOOT_ALIGN         equ 1 << 0              ; Выравнивание модулей по границе страницы
MULTIBOOT_MEMINFO       equ 1 << 1              ; Запрос информации о памяти
MULTIBOOT_VIDEO         equ 1 << 2              ; Запрос видеорежима
MULTIBOOT_FLAGS         equ MULTIBOOT_ALIGN | MULTIBOOT_MEMINFO | MULTIBOOT_VIDEO
MULTIBOOT_CHECKSUM      equ -(MULTIBOOT_MAGIC + MULTIBOOT_FLAGS)

; Размер стека (16 KB)
STACK_SIZE              equ 16384

; ============================================================================
; СЕКЦИЯ .multiboot - Multiboot header
; ============================================================================
; Должна быть в начале исполняемого файла (первые 8KB)
; GRUB ищет эту сигнатуру для определения загружаемого ядра
;
; Формат Multiboot header (с видеорежимом):
;   Offset 0:  magic
;   Offset 4:  flags
;   Offset 8:  checksum
;   Offset 12-28: address fields (обязательны позиционно, даже если bit 16 не установлен)
;   Offset 32: mode_type (0 = графический, 1 = текстовый)
;   Offset 36: width  (пикселей)
;   Offset 40: height (пикселей)
;   Offset 44: depth  (бит на пиксель)

section .multiboot
align 4
    dd MULTIBOOT_MAGIC                          ; Магическое число
    dd MULTIBOOT_FLAGS                          ; Флаги (align + meminfo + video)
    dd MULTIBOOT_CHECKSUM                       ; Контрольная сумма

    ; Поля адресов (offset 12-28) — не используются (bit 16 не установлен),
    ; но должны присутствовать для правильного смещения видео-полей
    dd 0                                        ; header_addr
    dd 0                                        ; load_addr
    dd 0                                        ; load_end_addr
    dd 0                                        ; bss_end_addr
    dd 0                                        ; entry_addr

    ; Поля видеорежима (offset 32-44) — используются при bit 2 в flags
    dd 0                                        ; mode_type: 0 = линейная графика
    dd 1024                                     ; width:  1024 пикселей
    dd 768                                      ; height: 768 пикселей
    dd 32                                       ; depth:  32 бита на пиксель (ARGB)

; ============================================================================
; СЕКЦИЯ .bss - Неинициализированные данные
; ============================================================================
; Здесь размещаем стек ядра

section .bss
align 16
stack_bottom:
    resb STACK_SIZE                             ; Резервируем 16KB для стека
stack_top:

; ============================================================================
; СЕКЦИЯ .text - Код
; ============================================================================

section .text

; Объявляем глобальные символы
global _start                                   ; Точка входа (для линкера)
extern kernel_main                              ; Главная функция на C

; ----------------------------------------------------------------------------
; _start - Точка входа в ядро
; ----------------------------------------------------------------------------
; Вызывается GRUB после загрузки ядра в память
; Регистры при входе:
;   EAX = 0x2BADB002 (магическое число Multiboot)
;   EBX = физический адрес структуры Multiboot info
; ----------------------------------------------------------------------------

_start:
    ; Настройка стека
    ; ESP (Stack Pointer) должен указывать на вершину стека
    ; Стек растёт вниз (от больших адресов к меньшим)
    mov esp, stack_top                          ; Устанавливаем указатель стека

    ; ------------------------------------------------------------------------
    ; Инициализация FPU (Этап 21)
    ; ------------------------------------------------------------------------
    ; stb_truetype и прочий "математический" код ядра использует double.
    ; Минимально: сбрасываем EM/TS в CR0 + fninit. GRUB уже оставил MP=1 по
    ; умолчанию и обработчик #MF (vector 16) в IDT будет установлен позже.
    ; ВАЖНО: EAX и EBX содержат параметры Multiboot, поэтому используем ECX.
    mov ecx, cr0
    and ecx, 0xFFFFFFF3     ; сбрасываем биты 2 (EM) и 3 (TS)
    mov cr0, ecx
    fninit                  ; полный сброс регистров FPU

    ; Сохраняем регистры Multiboot для передачи в kernel_main
    push ebx                                    ; Адрес Multiboot info structure
    push eax                                    ; Магическое число Multiboot

    ; Вызов главной функции ядра на C
    ; Сигнатура: void kernel_main(uint32_t magic, uint32_t addr)
    call kernel_main

    ; Если kernel_main вернёт управление (не должно происходить),
    ; останавливаем процессор

.hang:
    cli                                         ; Отключаем прерывания
    hlt                                         ; Останавливаем процессор
    jmp .hang                                   ; Бесконечный цикл на случай NMI
