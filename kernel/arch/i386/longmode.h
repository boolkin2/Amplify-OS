// ============================================================================
// longmode.h — Этап 33A: подготовка и демонстрация Long Mode (x86_64)
// ============================================================================
// Этот модуль:
//   1. Детектирует возможности процессора через CPUID:
//        — Long Mode (CPUID 0x80000001 EDX bit 29)
//        — PAE (CPUID 0x00000001 EDX bit 6)
//        — NX bit (CPUID 0x80000001 EDX bit 20)
//        — RDTSC, FPU, SSE, SSE2 — для информации.
//   2. Строит 4-уровневую таблицу страниц PML4, identity-маппирующую
//      первые 4 GB физической памяти 2-MB страницами.
//      Структура полностью совместима с x86_64 IA-32e:
//         PML4 (1 запись) -> PDPT (4 записи) -> PD (4×512 записей)
//      Всё хранится в 16-KB выровненных буферах в .bss ядра.
//   3. Делает ОДНОКРАТНЫЙ "round-trip" в Long Mode:
//        32-bit protected -> Long Mode (compat) -> 64-bit Long Mode
//        записывает в фиксированный физ.адрес (0x00007F00) сигнатуру
//        'AMPLIFY64' и 64-битное значение из RAX, читаемое только
//        в 64-bit режиме.
//        затем возвращается в 32-bit protected mode и продолжает работу.
//   4. Возвращает структуру с результатами для отображения
//      в приложении «Сведения» (sysinfo).
//
// ВАЖНО: переход в Long Mode и обратно делается с выключенными
// прерываниями и делает временные изменения в CR0/CR3/CR4/EFER.
// Модуль защищён двойным флагом lm_demo_done — выполняется ТОЛЬКО
// один раз, чтобы не дестабилизировать ядро.
// ============================================================================

#ifndef LONGMODE_H
#define LONGMODE_H

#include <stdint.h>
#include <stdbool.h>

// ----------------------------------------------------------------------------
// Сводная информация о возможностях процессора (для UI «Сведения»)
// ----------------------------------------------------------------------------
typedef struct {
    char     vendor[13];     // Например, "GenuineIntel" или "AuthenticAMD".
    char     brand[49];      // Brand string CPUID 0x80000002..04 (если есть).
    uint32_t max_basic_leaf; // Максимальный номер CPUID basic-функций.
    uint32_t max_ext_leaf;   // Максимальный номер CPUID extended-функций.

    bool fpu;        // x87 FPU (CPUID 1 EDX bit 0).
    bool pae;        // PAE (CPUID 1 EDX bit 6).
    bool apic;       // Local APIC (CPUID 1 EDX bit 9).
    bool sse;        // SSE (CPUID 1 EDX bit 25).
    bool sse2;       // SSE2 (CPUID 1 EDX bit 26).
    bool nx;         // NX bit (CPUID 0x80000001 EDX bit 20).
    bool long_mode;  // Long Mode (CPUID 0x80000001 EDX bit 29).
    bool rdtscp;     // RDTSCP (CPUID 0x80000001 EDX bit 27).
    bool x64_1gb_pages;  // 1-GB страницы (CPUID 0x80000001 EDX bit 26).
} cpu_info_t;

// ----------------------------------------------------------------------------
// Результат демонстрации Long Mode
// ----------------------------------------------------------------------------
typedef struct {
    bool     attempted;       // Пробовали ли запустить демо.
    bool     supported;       // CPU поддерживает Long Mode.
    bool     pml4_built;      // PML4 успешно построен.
    bool     entered_lm;      // Удалось войти в Long Mode (получили сигнатуру).
    bool     returned_ok;     // Корректно вернулись в 32-bit protected.
    uint32_t pml4_phys;       // Физический адрес PML4 (для отладки/UI).
    uint64_t signature;       // 64-битное значение, записанное в LM.
                              // Должно равняться 0x414D504C49463634ULL ("AMPLIF64").
} lm_demo_result_t;

// ----------------------------------------------------------------------------
// API
// ----------------------------------------------------------------------------

// Заполнить cpu_info_t текущей информацией о процессоре.
void lm_query_cpu(cpu_info_t* out);

// Построить 4-уровневую таблицу страниц PML4 (identity-map 0..4 GB).
// Возвращает физический адрес PML4. Идемпотентно.
uint32_t lm_build_pml4(void);

// Запустить однократную демонстрацию входа в Long Mode и возврата.
// Заполняет переданную структуру результата.
// Возвращает true, если демо прошло успешно (вошли в LM и вернулись).
bool lm_run_demo(lm_demo_result_t* out);

// Получить последний результат демо (после lm_run_demo).
const lm_demo_result_t* lm_last_result(void);

// Удобная инициализация в boot-time: заполняет CPU info, строит PML4
// и запускает демо. Безопасно вызывать после полной инициализации
// памяти и до старта планировщика. Если CPU не поддерживает LM —
// просто заполняет cpu_info и помечает demo как unsupported.
void longmode_init(void);

// Доступ к закешированной cpu_info_t (для UI).
const cpu_info_t* lm_cpu_info(void);

#endif // LONGMODE_H
