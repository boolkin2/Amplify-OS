; ============================================================================
; irq.asm - Обработчики аппаратных прерываний (IRQ 0-15)
; ============================================================================
; Interrupt Request Handlers для аппаратных устройств
; IRQ переназначены на прерывания 32-47
; ============================================================================

[BITS 32]

section .text

; Экспортируем обработчики для использования в C
global irq0, irq1, irq2, irq3, irq4, irq5, irq6, irq7
global irq8, irq9, irq10, irq11, irq12, irq13, irq14, irq15

; Импортируем общий обработчик из C
extern irq_handler

; ============================================================================
; Макрос для создания обработчиков IRQ
; ============================================================================

; IRQ не имеют кода ошибки, поэтому всегда добавляем 0
%macro IRQ 2
irq%1:
    cli                             ; Отключаем прерывания
    push byte 0                     ; Фиктивный код ошибки
    push byte %2                    ; Номер прерывания (32 + IRQ номер)
    jmp irq_common_stub             ; Переход к общему обработчику
%endmacro

; ============================================================================
; Определение обработчиков IRQ (0-15)
; ============================================================================

IRQ  0,  32     ; IRQ0:  Системный таймер (PIT)
IRQ  1,  33     ; IRQ1:  Клавиатура
IRQ  2,  34     ; IRQ2:  Каскад (подчинённый PIC)
IRQ  3,  35     ; IRQ3:  COM2
IRQ  4,  36     ; IRQ4:  COM1
IRQ  5,  37     ; IRQ5:  LPT2
IRQ  6,  38     ; IRQ6:  Floppy disk
IRQ  7,  39     ; IRQ7:  LPT1
IRQ  8,  40     ; IRQ8:  CMOS Real-time clock
IRQ  9,  41     ; IRQ9:  Свободно
IRQ 10,  42     ; IRQ10: Свободно
IRQ 11,  43     ; IRQ11: Свободно
IRQ 12,  44     ; IRQ12: PS/2 мышь
IRQ 13,  45     ; IRQ13: FPU
IRQ 14,  46     ; IRQ14: Primary ATA
IRQ 15,  47     ; IRQ15: Secondary ATA

; ============================================================================
; Общий обработчик IRQ
; ============================================================================
; Вызывается всеми IRQ после сохранения номера прерывания
; Сохраняет все регистры и вызывает обработчик на C

irq_common_stub:
    ; Сохраняем все регистры общего назначения
    pusha                           ; Сохраняет EAX, ECX, EDX, EBX, ESP, EBP, ESI, EDI

    ; Сохраняем сегментные регистры
    mov ax, ds                      ; Сохраняем DS
    push eax

    ; Загружаем сегмент данных ядра
    mov ax, 0x10                    ; 0x10 = селектор данных ядра
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax

    ; Вызываем обработчик на C
    ; Передаём указатель на структуру registers_t (ESP указывает на неё)
    push esp                        ; Передаём указатель на стек (registers_t*)
    call irq_handler                ; Вызов обработчика на C
    mov esp, eax                    ; NEW: Устанавливаем новый указатель стека, возвращённый из C (task_switch)

    ; Восстанавливаем сегментные регистры
    pop eax                         ; Восстанавливаем DS
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax

    ; Восстанавливаем регистры общего назначения
    popa                            ; Восстанавливает EDI, ESI, EBP, ESP, EBX, EDX, ECX, EAX

    ; Очищаем код ошибки и номер прерывания
    add esp, 8                      ; Убираем int_no и err_code

    ; Включаем прерывания и возвращаемся
    sti                             ; Включить прерывания
    iret                            ; Возврат из прерывания (восстанавливает EIP, CS, EFLAGS)
