// ============================================================================
// power.h - Управление питанием: reboot / shutdown
// ============================================================================
// Единый API, которым могут пользоваться shell и GUI (меню Пуск).
// ============================================================================

#ifndef POWER_H
#define POWER_H

// Аппаратный reset через контроллер клавиатуры 8042 (порт 0x64, команда 0xFE).
// В QEMU срабатывает немедленно; на реальном железе часто тоже. Не
// возвращается; если вдруг вернулась — бесконечный hlt.
void power_reboot(void) __attribute__((noreturn));

// Выключение через QEMU ACPI-порт. Если не сработало — тушит прерывания
// и падает в бесконечный hlt (экран остаётся на последнем кадре).
void power_shutdown(void) __attribute__((noreturn));

// ============================================================================
// «Шторка» завершения работы / перезагрузки
// ============================================================================
// Рисует полноэкранную тёмно-синюю шторку с надписью «Завершение работы
// AMPLIFY-OS…» (или «Перезагрузка AMPLIFY-OS…»), небольшой анимацией точек
// и спиннером, удерживает её ~0.8 секунды, после чего вызывает реальный
// power_shutdown / power_reboot. Используется кнопками меню Пуск.
void power_shutdown_with_curtain(void) __attribute__((noreturn));
void power_reboot_with_curtain(void)   __attribute__((noreturn));

#endif // POWER_H
