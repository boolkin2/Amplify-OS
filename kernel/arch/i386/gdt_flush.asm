; ============================================================================
; gdt_flush.asm - Загрузка GDT в процессор
; ============================================================================
; Эта функция загружает новую GDT в регистр GDTR и обновляет
; все сегментные регистры для использования новых дескрипторов
; ============================================================================

[BITS 32]

section .text

; Экспортируем функцию для использования в C
global gdt_flush
global tss_flush

; ----------------------------------------------------------------------------
; gdt_flush - Загрузка GDT и обновление сегментных регистров
; ----------------------------------------------------------------------------
; Параметры:
;   [esp + 4] = адрес структуры gdt_ptr_t
; ----------------------------------------------------------------------------

gdt_flush:
    ; Получаем адрес gdt_ptr из стека
    mov eax, [esp + 4]              ; EAX = адрес gdt_ptr_t

    ; Загружаем GDT в регистр GDTR
    ; LGDT загружает 6 байт: 2 байта лимит + 4 байта база
    lgdt [eax]                      ; Загрузить GDT

    ; Обновляем сегментные регистры данных
    ; Все сегменты данных (DS, ES, FS, GS, SS) указывают на
    ; дескриптор данных ядра (селектор 0x10)
    
    mov ax, 0x10                    ; 0x10 = селектор данных ядра (GDT entry 2)
    mov ds, ax                      ; Data Segment
    mov es, ax                      ; Extra Segment
    mov fs, ax                      ; FS Segment
    mov gs, ax                      ; GS Segment
    mov ss, ax                      ; Stack Segment

    ; Обновляем сегмент кода (CS)
    ; CS нельзя загрузить напрямую через MOV
    ; Используем дальний переход (far jump) для загрузки нового CS
    ; Формат: jmp selector:offset
    
    jmp 0x08:.flush                 ; 0x08 = селектор кода ядра (GDT entry 1)
                                    ; Дальний переход на метку .flush

.flush:
    ; После дальнего перехода CS = 0x08 (код ядра)
    ; Все сегментные регистры обновлены
    ret                             ; Возврат в C код

; ----------------------------------------------------------------------------
; tss_flush - Загрузка Task Register
; ----------------------------------------------------------------------------
tss_flush:
    mov ax, 0x2B    ; Индекс дескриптора TSS = 5 (5 * 8 = 0x28).
                    ; Младшие 2 бита (RPL) = 3 (чтобы разрешить вызов из ring 3? Нет, обычно 0, но 0x2B = 0x28 | 3)
                    ; Для ltr RPL не имеет значения, но стандартно 0x28.
    mov ax, 0x28    ; Используем селектор 0x28 (GDT_TSS)
    ltr ax
    ret
