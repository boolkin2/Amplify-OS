; ============================================================================
; idt_flush.asm - Загрузка IDT в процессор
; ============================================================================
; Эта функция загружает новую IDT в регистр IDTR
; ============================================================================

[BITS 32]

section .text

; Экспортируем функцию для использования в C
global idt_flush

; ----------------------------------------------------------------------------
; idt_flush - Загрузка IDT
; ----------------------------------------------------------------------------
; Параметры:
;   [esp + 4] = адрес структуры idt_ptr_t
; ----------------------------------------------------------------------------

idt_flush:
    ; Получаем адрес idt_ptr из стека
    mov eax, [esp + 4]              ; EAX = адрес idt_ptr_t

    ; Загружаем IDT в регистр IDTR
    ; LIDT загружает 6 байт: 2 байта лимит + 4 байта база
    lidt [eax]                      ; Загрузить IDT

    ; Включаем прерывания
    sti                             ; Set Interrupt Flag (разрешить прерывания)

    ret                             ; Возврат в C код
