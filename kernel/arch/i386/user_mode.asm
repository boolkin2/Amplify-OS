; ============================================================================
; user_mode.asm - Переключение в User Mode (Ring 3)
; ============================================================================

[BITS 32]

section .text

global jump_to_user_mode

; ----------------------------------------------------------------------------
; void jump_to_user_mode(uint32_t eip, uint32_t esp);
; ----------------------------------------------------------------------------
jump_to_user_mode:
    ; Получаем параметры из стека
    mov eax, [esp + 4]      ; EIP
    mov ebx, [esp + 8]      ; ESP

    ; Обновляем сегменты данных для Ring 3
    ; Селектор пользовательских данных: 0x20 (индекс 4 * 8)
    ; Устанавливаем RPL = 3 -> 0x20 | 3 = 0x23
    mov cx, 0x23
    mov ds, cx
    mov es, cx
    mov fs, cx
    mov gs, cx

    ; Для перехода в Ring 3 мы должны сымитировать возврат из прерывания (iret).
    ; Инструкция iret ожидает на стеке: SS, ESP, EFLAGS, CS, EIP.

    push 0x23               ; SS (селектор пользовательских данных с RPL 3)
    push ebx                ; ESP пользователя
    
    ; Получаем текущие EFLAGS и устанавливаем бит IF (прерывания включены)
    pushf
    pop ecx
    or ecx, 0x200           ; Установить IF (бит 9)
    push ecx                ; Сохранить измененные EFLAGS на стек
    
    ; Селектор пользовательского кода: 0x18 (индекс 3 * 8)
    ; RPL = 3 -> 0x18 | 3 = 0x1B
    push 0x1B               ; CS (селектор пользовательского кода с RPL 3)
    
    push eax                ; EIP (точка входа приложения)

    ; iret снимет EIP, CS, EFLAGS, ESP, SS со стека
    ; и процессор перейдет в Ring 3
    iret
