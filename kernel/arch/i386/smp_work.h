// ============================================================================
// smp_work.h - простая распределённая очередь задач для AP'шек.
// ----------------------------------------------------------------------------
// До этого этапа AP'шки крутили чисто декоративную busy/idle петлю — реальные
// задачи (рендер кадра, парсинг пакета, ресэмплинг звука) всё равно бежали на
// BSP. Теперь любой код может постить «работу» (`work_fn_t`) в общую очередь;
// первый освободившийся AP подберёт её на ходу и выполнит как часть своей
// busy-фазы. Если все APы заняты, BSP может сам выбрать из очереди (так
// получается work-stealing-стиль балансировка).
//
// Очередь это кольцевой буфер фиксированного размера под spinlock'ом —
// простая, проверяемая, не lock-free, но более чем достаточная для нашего
// темпа задач (десятки в секунду).
//
// API:
//   smp_work_init()         — вызвать один раз на BSP до запуска APов.
//   smp_post_work(fn, arg)  — постит задачу. false если очередь забита.
//   smp_run_one_if_any()    — пытается забрать одну задачу и выполнить её.
//                              Возвращает true, если работа была. AP'шка
//                              регулярно дёргает это в своей петле.
//   smp_work_pending()      — приблизительная глубина очереди (для UI).
// ============================================================================
#ifndef SMP_WORK_H
#define SMP_WORK_H

#include <stdint.h>
#include <stdbool.h>

typedef void (*work_fn_t)(void* arg);

void smp_work_init(void);
bool smp_post_work(work_fn_t fn, void* arg);
bool smp_run_one_if_any(void);
uint32_t smp_work_pending(void);

// Для статистики UI: сколько задач выполнено каждым CPU суммарно.
extern volatile uint32_t cpu_jobs_done[];

#endif // SMP_WORK_H
