// ============================================================================
// rtc.h — Real-Time Clock (CMOS, MC146818) для AMPLIFY-OS x86_64.
// ----------------------------------------------------------------------------
// Регистровый интерфейс совместим со всеми x86 (порт 0x70/0x71). Эта
// реализация — портирование kernel/drivers/rtc.c один-в-один: 64-bit
// арифметика не требуется, хватит uint8_t/uint16_t.
// ============================================================================
#ifndef AOS_X86_64_RTC_H
#define AOS_X86_64_RTC_H

#include <stdint.h>

typedef struct {
    uint8_t  second;   // 0..59
    uint8_t  minute;   // 0..59
    uint8_t  hour;     // 0..23
    uint8_t  day;      // 1..31
    uint8_t  month;    // 1..12
    uint16_t year;     // 4-значный (например 2026)
} rtc_time_t;

// Прочитать текущее время из CMOS. Корректно обрабатывает BCD/binary режимы
// и 12/24-часовой формат, ждёт окончания update-цикла RTC, чтобы не получить
// «промежуточное» значение во время инкремента секунд.
void rtc_read(rtc_time_t* out);

#endif
