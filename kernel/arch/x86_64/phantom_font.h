// ============================================================================
// phantom_font.h — шрифт текстового экрана гостя phantom (этап 50.5).
// ----------------------------------------------------------------------------
// Гость пишет в видеопамять коды CP437 и ждёт экран 80x25. Шрифты интерфейса
// (ui_font) для этого не подходят: кодировка у них CP1251, а моноширинных
// размеров два — мелких. Здесь — та же гарнитура DejaVu, но в CP437 и в
// нескольких размерах знакоместа: окно гостя берёт самый крупный, при котором
// экран помещается целиком, и рисует без растяжения.
// Данные — phantom_font_data.c (генерирует tools/gen_phantom_font.py).
// ============================================================================
#ifndef AOS_X86_64_PHANTOM_FONT_H
#define AOS_X86_64_PHANTOM_FONT_H

#include <stdint.h>

typedef struct {
    uint8_t  w, h;              // рамка глифа, пиксели (0 — знакоместо пустое)
    uint8_t  left, top;         // где она стоит внутри знакоместа
    uint32_t off;               // смещение покрытия в blob
} pf_glyph_t;

typedef struct {
    uint8_t           cell_w, cell_h;
    const pf_glyph_t* glyphs;   // 256 записей, индекс — код CP437
    const uint8_t*    blob;     // 4 бита на пиксель, строка добита до байта
} pf_face_t;

#define PHANTOM_FONT_FACES 7
extern const pf_face_t phantom_font_faces[PHANTOM_FONT_FACES];   // по возрастанию размера

#endif
