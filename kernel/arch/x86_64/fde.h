// ============================================================================
// fde.h — Full Disk Encryption системного раздела AMPLIFY-OS (этап 48).
// ----------------------------------------------------------------------------
// Слои:
//
//   fat32.c          /disk — обычный FAT32, ничего не знает о шифровании
//      │  сектора vdev
//   blkcrypt.c       dm-crypt-аналог: aes-xts-plain64, ключ в памяти
//      │  шифротекст
//   disk_io / ata    физический раздел AMPLIFY-SYSTEM (тип «Linux LUKS»)
//
//   luks.c           заголовок LUKS1 в начале раздела: 8 слотов пароля,
//                    мастер-ключ под AF-splitter'ом, PBKDF2-HMAC-SHA256
//
// Этот модуль — политика поверх них:
//   * fde_scan()   — на загрузке, если /disk не смонтирован, ищет LUKS-раздел
//                    и помечает системный том как запертый;
//   * fde_unlock() — пароль → мастер-ключ → blkcrypt → fat32_mount_volume;
//   * экран разблокировки (fde_unlock.c) показывается ДО amply/firstboot/
//     login, т.е. до первого обращения к /disk;
//   * «единый вход»: если пароль тома совпадает с паролем пользователя
//     (так делает установщик), экран входа пропускается.
//
// Против чего защищает: офлайн-доступ к диску (украденный ноутбук / образ).
// НЕ защищает от компрометации работающей системы — ключ в RAM, пока
// система запущена.  ESP с ядром и initrd не шифруется (как у Linux без
// Secure Boot): подмена ядра — отдельная угроза, её закрывает подпись.
// ============================================================================
#ifndef AOS_X86_64_FDE_H
#define AOS_X86_64_FDE_H

#include <stdint.h>
#include <stdbool.h>

// Сколько миллисекунд ЭТОЙ машины занимает проверка пароля (PBKDF2
// подбирается бенчмарком при создании слота).  cryptsetup по умолчанию
// берёт 2 с; мы — 1 с, чтобы загрузка оставалась быстрой.
#define FDE_ITER_MS 1000

// ---- Системный том ------------------------------------------------------------
void        fde_scan(void);          // после fat32_mount()
bool        fde_pending(void);       // найден запертый системный том
bool        fde_unlocked(void);      // том открыт и смонтирован как /disk
int         fde_unlock(const char* passphrase);   // LUKS_OK / LUKS_BAD_PASS / ...
const char* fde_status_str(void);    // "not encrypted" / "locked" / "unlocked"

// Описание тома для экрана разблокировки: "QEMU HARDDISK  ·  3.7 GB".
const char* fde_volume_label(void);

// Пароль последней успешной разблокировки для единого входа.  Отдаётся
// ОДИН раз и сразу затирается.
bool        fde_take_sso(char* out, int cap);

// Сменить пароль тома: новый слот + уничтожение старого.  Данные не
// перешифровываются (мастер-ключ прежний).  LUKS_OK / LUKS_BAD_PASS / ...
int         fde_change_passphrase(const char* old_pass, const char* new_pass);

// Многострочный отчёт для `seal status`.
void        fde_describe(char* out, int cap);

// ---- Self-test (RAM-диск, вызывается из smoke 48 и `seal selftest`) ----------
// LUKS format/probe/open (верный и неверный пароль), шифрование через
// blkcrypt, «на диске — шум», разные шифротексты одинаковых секторов,
// добавление/уничтожение слотов.  Подробности — в serial.
bool        fde_self_test(void);

// ---- Экран разблокировки (fde_unlock.c) ---------------------------------------
// Блокируется, пока пароль не подойдёт; после возврата /disk смонтирован.
void        fde_unlock_screen(void);

#endif
