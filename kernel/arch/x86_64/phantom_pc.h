// ============================================================================
// phantom_pc.h — «материнская плата» гостя phantom (этап 50.2).
// ----------------------------------------------------------------------------
// Минимальный IBM PC, которого хватает ядру Linux, чтобы загрузиться и жить:
//   * пара контроллеров прерываний 8259 (локального APIC у гостя нет);
//   * таймер 8254: канал 0 даёт IRQ0, канал 2 — замеры через порт 0x61;
//   * последовательный порт 16550A на 0x3F8 / IRQ4 — консоль гостя;
//   * часы CMOS, порт быстрого A20 и сброс;
//   * [50.4] шина PCI с диском virtio-blk (если диск дали — pc_attach_disk) и
//     регистры видеоконтроллера 3D4/3D5 (начало экрана, курсор);
//   * [50.5] контроллер клавиатуры 8042 (порты 0x60/0x64, IRQ1) с клавиатурой.
// Всё остальное пространство портов пусто: чтение даёт единицы, запись
// пропадает — как на шине без устройства.
//
// Устройства исполняются на AP гостя (обработчик выходов и три вопроса о
// прерываниях — hv_model_t), поэтому здесь только вычисления над заранее
// выделенной структурой. С BSP платформа видна через два кольца: вывод
// консоли гостя (AP пишет, BSP читает) и ввод (BSP пишет, AP читает).
// Время устройств — TSC хоста: гость видит тот же TSC, так что его таймеры
// и его часы идут с одной скоростью.
// ============================================================================
#ifndef AOS_X86_64_PHANTOM_PC_H
#define AOS_X86_64_PHANTOM_PC_H

#include "hv.h"

typedef struct pc pc_t;

typedef struct {
    uint64_t irq0, irq4;            // сколько раз подняты прерывания таймера и порта
    uint64_t tx, rx;                // символов от гостя и гостю
    uint64_t tx_lost;               // не поместилось в кольцо вывода
    uint64_t unknown_io;            // обращений к портам, за которыми ничего нет
    uint16_t last_unknown_port;
    uint64_t blk_reqs, blk_sectors; // запросов к диску и прочитанных секторов (по 512)
    uint64_t blk_errors;            // запросов, на которые диск ответил ошибкой
    uint64_t irq1, kbd;             // [50.5] прерываний клавиатуры и скан-кодов, отданных гостю
    int      reset;                 // гость попросил сброс (порт 0x64/0x92/0xCF9)
    int      end_reason;            // последний HV_EXIT_*, дошедший до платформы
} pc_stats_t;

// BSP. Платформа одна (статическая память): вторая ВМ с PC пока не нужна.
// unix_now — время на стене в секундах Unix для часов CMOS.
pc_t*             pc_create(hv_vm_t* vm, uint64_t unix_now);
void              pc_destroy(pc_t* pc);
const hv_model_t* pc_model(void);
const pc_stats_t* pc_stats(pc_t* pc);

// Консоль гостя. read — забрать вывод (число байт); input — подать ввод и
// разбудить гостя, false — кольцо ввода полно.
int  pc_console_read(pc_t* pc, char* buf, int max);
bool pc_console_input(pc_t* pc, const char* s, int n);

// [50.4] BSP, до старта гостя: дать гостю диск. Появляется шина PCI с двумя
// устройствами — мостом и диском virtio-blk (только чтение); содержимое диска
// — data[0..bytes) в памяти хоста, жить оно должно дольше гостя.
void pc_attach_disk(pc_t* pc, const uint8_t* data, uint64_t bytes);

// [50.4] Текстовый экран гостя: с какого знакоместа в видеопамяти (B8000,
// окно 32 КБ) начинается видимая часть и где курсор. Ядро Linux прокручивает
// экран не копированием, а сдвигом этого начала (регистры 0Ch/0Dh
// видеоконтроллера) — читать «первые 25 строк» значит видеть застывший кадр.
uint32_t pc_vga_origin(pc_t* pc);
uint32_t pc_vga_cursor(pc_t* pc);
bool     pc_vga_cursor_on(pc_t* pc);            // [50.5] курсор не спрятан гостем

// [50.5] Клавиатура гостя (контроллер 8042, IRQ1). BSP: подать скан-код
// набора 1 (нажатие или отпускание; префикс E0 — отдельным вызовом). Можно
// звать из обработчика прерывания; из главного потока — только с IF=0.
// false — очередь полна (гость не читает клавиатуру).
bool pc_kbd_scancode(pc_t* pc, uint8_t sc);

// Секунды Unix из календарной даты (для часов гостя).
uint64_t pc_unix_time(int year, int month, int day, int hour, int minute, int second);

// ---- [50.3] для BIOS гостя (phantom_bios.c) -------------------------------------
// BSP, до старта гостя: привести плату в состояние, в котором её оставляет
// BIOS — таймер тикает 18.2 раза в секунду, IRQ0 открыт, базы векторов 08h/70h.
void pc_bios_defaults(pc_t* pc);
// BSP: кому отдавать VMCALL гостя (так вызываются службы BIOS).
typedef int (*pc_vmcall_fn)(hv_vm_t* vm, void* ctx);    // на AP; ответ HV_RESUME/HV_STOP
void pc_set_vmcall(pc_t* pc, pc_vmcall_fn fn, void* ctx);
// Остальное — на AP гостя, из службы BIOS.
void     pc_con_putc(pc_t* pc, char ch);        // символ на консоль гостя
int      pc_con_peek(pc_t* pc);                 // введённый символ, не забирая; -1 — нет
int      pc_con_getc(pc_t* pc);                 // забрать введённый символ; -1 — нет
bool     pc_irq_in_service(pc_t* pc, int irq);  // прерывание сейчас обслуживается?
void     pc_irq_eoi(pc_t* pc, int irq);         // закончить его обслуживание
uint64_t pc_unix_now(pc_t* pc);                 // время на стене у гостя
int      pc_kbd_take(pc_t* pc);                 // [50.5] байт клавиатуры (как чтение порта 0x60); -1 — нет
void     pc_vga_set_cursor(pc_t* pc, uint32_t pos);  // [50.5] курсор: номер знакоместа от начала экрана

#endif
