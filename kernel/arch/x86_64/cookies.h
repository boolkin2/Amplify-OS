// ============================================================================
// cookies.h — хранилище cookies браузера (подэтап 48.2, «интернет до конца»).
// ----------------------------------------------------------------------------
// Зачем: многие сайты первым ответом ставят cookie и тут же перенаправляют на
// тот же адрес, ожидая её обратно (страницы согласия, защита от ботов,
// выбор языка). Без cookies это бесконечная петля редиректов.
// Хранилище — в памяти, до перезагрузки (срок жизни не учитывается, на диск
// не пишется): COOKIE_MAX записей, вытеснение старейшей.
// Учитывается: Domain (cookie поддомена сайт поставить может только себе и
// своему домену), Path (префикс), Secure (только по https), удаление через
// Max-Age=0 или пустое значение. Не учитывается: Expires, SameSite, HttpOnly
// (скриптов у нас нет — все cookies и так «HttpOnly»).
// ============================================================================
#ifndef AOS_X86_64_COOKIES_H
#define AOS_X86_64_COOKIES_H

#include <stddef.h>
#include <stdbool.h>

#define COOKIE_MAX 48

// Разобрать все строки Set-Cookie из заголовков ответа сайта host.
void cookies_store(const char* host, const char* hdrs, size_t hlen);
// Строка "Cookie: a=1; b=2\r\n" для запроса (или пустая). Возвращает длину.
int  cookies_header(const char* host, const char* path, bool https, char* out, int cap);
void cookies_clear(void);
int  cookies_count(void);

#endif
