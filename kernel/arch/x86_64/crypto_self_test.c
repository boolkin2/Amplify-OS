// Простой ASN.1 sanity: SEQUENCE {INTEGER 42}.  Длина: tag(1) + len(1) + INT-tag(1) +
// INT-len(1) + INT-value(1) = 5.
static int test_asn1(void) {
    static const uint8_t der[] = { 0x30, 0x03, 0x02, 0x01, 0x2A };
    asn1_t outer;
    if (!asn1_parse(der, sizeof(der), &outer)) return 0;
    if (outer.tag != ASN1_TAG_SEQUENCE)        return 0;
    if (outer.len != 3)                        return 0;
    asn1_t inner;
    if (!asn1_parse(outer.val, outer.len, &inner)) return 0;
    if (inner.tag != ASN1_TAG_INTEGER)             return 0;
    uint32_t v;
    if (!asn1_int_to_u32(&inner, &v) || v != 42)   return 0;

    // Long-form length: SEQUENCE { OCTET STRING 200 bytes of 0xAB }
    static uint8_t long_der[6 + 200];
    long_der[0] = 0x30; long_der[1] = 0x81; long_der[2] = 200 + 3;
    long_der[3] = 0x04; long_der[4] = 0x81; long_der[5] = 200;
    for (int i = 0; i < 200; i++) long_der[6 + i] = 0xAB;
    asn1_t outer2;
    if (!asn1_parse(long_der, 6 + 200, &outer2))    return 0;
    if (outer2.len != 200u + 3u)                    return 0;
    return 1;
}

// X.509 parsing — берём ISRG Root X1 из trust store и парсим.
static int test_x509_parse(void) {
    if (g_crypto_ca_count < 1) return 0;
    // [48.2] Хранилище теперь — весь набор Mozilla в алфавитном порядке, и
    // первым стоит уже не ISRG Root X1: ищем его по имени (инварианты ниже
    // написаны под него — RSA-4096, выпущен в 2015 году).
    size_t idx = g_crypto_ca_count;
    for (size_t i = 0; i < g_crypto_ca_count; i++) {
        const char* a = g_crypto_ca_store[i].name;
        const char* b = "ISRG Root X1";
        size_t k = 0;
        while (a[k] && a[k] == b[k]) k++;
        if (a[k] == 0 && b[k] == 0) { idx = i; break; }
    }
    if (idx == g_crypto_ca_count) return 0;
    x509_cert_t cert;
    if (!x509_parse(g_crypto_ca_store[idx].der, g_crypto_ca_store[idx].der_len, &cert)) {
        return 0;
    }
    // Проверим инварианты:
    //   * sig_alg != UNKNOWN  (ISRG X1 = RSA-SHA256)
    //   * Subject == Issuer (root self-signed)
    //   * is_ca должен быть true для root
    //   * not_before < not_after, разумные годы (2015–2035)
    if (cert.sig_alg == X509_SIG_UNKNOWN) return 0;
    if (cert.subject_dn_len != cert.issuer_dn_len) return 0;
    for (size_t i = 0; i < cert.subject_dn_len; i++) {
        if (cert.subject_dn[i] != cert.issuer_dn[i]) return 0;
    }
    if (!cert.is_ca) return 0;
    // 1420000000 (~2015-01-01) ... 2050000000 (~2034-12-31)
    if (cert.not_before < 1420000000ULL || cert.not_before > 2050000000ULL) return 0;
    if (cert.not_after  <= cert.not_before) return 0;
    if (cert.pk_type    != X509_PK_RSA) return 0;
    // RSA-4096 = 512 bytes modulus.  Допускаем 256..513 bytes.
    if (cert.rsa_modulus_len < 256 || cert.rsa_modulus_len > 513) return 0;
    if (cert.rsa_exponent   != 65537) return 0;
    return 1;
}

// X.509 self-signature verify: root CA должна быть подписана самой собой.
// [48.2] В хранилище теперь 150 корней: проверять подпись каждого при каждой
// загрузке — это +1.7 с к старту (RSA-4096 нашей арифметикой небыстр), и так
// дважды (здесь и в smoke 47.3). Проверяем по одному корню каждого вида
// ключа — RSA, P-256, P-384: этого достаточно, чтобы поймать поломку
// проверки подписи; целостность самих данных — дело сборки.
static int test_x509_verify(void) {
    bool seen[4] = { false, false, false, false };   // RSA, P-256, P-384, прочее
    int checked = 0;
    for (size_t i = 0; i < g_crypto_ca_count && checked < 3; i++) {
        x509_cert_t cert;
        if (!x509_parse(g_crypto_ca_store[i].der, g_crypto_ca_store[i].der_len, &cert)) {
            continue;
        }
        int kind = cert.pk_type == X509_PK_RSA ? 0 : cert.pk_type == X509_PK_EC_P256 ? 1 :
                   cert.pk_type == X509_PK_EC_P384 ? 2 : 3;
        if (kind == 3 || seen[kind]) continue;
        seen[kind] = true;
        if (!x509_verify_signature(&cert, &cert)) return 0;
        checked++;
    }
    return checked >= 1;
}

// Поиск root CA по issuer DN: используем DN самого root'а как issuer →
// должен найти сам root.
static int test_ca_lookup(void) {
    if (g_crypto_ca_count < 1) return 0;
    x509_cert_t root;
    if (!x509_parse(g_crypto_ca_store[0].der, g_crypto_ca_store[0].der_len, &root)) {
        return 0;
    }
    x509_cert_t found;
    if (!crypto_ca_find_by_dn(root.subject_dn, root.subject_dn_len, &found)) return 0;
    // Должны быть одинаковые subject DNs.
    if (found.subject_dn_len != root.subject_dn_len) return 0;
    for (size_t i = 0; i < root.subject_dn_len; i++) {
        if (found.subject_dn[i] != root.subject_dn[i]) return 0;
    }
    // Negative: фиктивный DN не должен находиться.
    uint8_t fake[] = { 0x30, 0x04, 0x55, 0x04, 0x03, 0x00 };
    x509_cert_t notfound;
    if (crypto_ca_find_by_dn(fake, sizeof(fake), &notfound)) return 0;
    return 1;
}

