static int eq(const uint8_t* a, const uint8_t* b, size_t n) {
    for (size_t i = 0; i < n; i++) if (a[i] != b[i]) return 0;
    return 1;
}

static void dbg_hex(const char* label, const uint8_t* p, int n) {
    serial_puts("  ");
    serial_puts(label);
    serial_puts(" = ");
    static const char hex[] = "0123456789abcdef";
    for (int i = 0; i < n; i++) {
        char b[3] = { hex[p[i] >> 4], hex[p[i] & 0xf], 0 };
        serial_puts(b);
    }
    serial_puts("\n");
}

