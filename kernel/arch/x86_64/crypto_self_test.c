// ============================================================================
// crypto_self_test.c — Known Answer Tests для всех примитивов (этап 47.1).
// ----------------------------------------------------------------------------
// Каждый алгоритм проверяется на standard test vector'ах:
//   * SHA-256:  FIPS 180-2  Appendix B.2   ("abc")
//   * SHA-384:  FIPS 180-2  Appendix D.1   ("abc")
//   * SHA-512:  FIPS 180-2  Appendix C.1   ("abc")
//   * HMAC-SHA256: RFC 4231 Test Case 1    (20-байтовый ключ 0x0b)
//   * HMAC-SHA384: RFC 4231 Test Case 2    (ключ "Jefe")
//   * AES-128 ECB: FIPS-197 Appendix B     ("00112233...ff" plaintext)
//   * AES-256 ECB: NIST CAVS                (Encrypt-AES256.txt #0)
//   * AES-CBC:    NIST SP 800-38A F.2.1    (AES-128-CBC sample)
//   * AES-GCM:    NIST GCM Test Vector #1  (zero key, zero IV, zero text)
//   * ChaCha20:   RFC 8439 §2.4.2         (sunscreen test vector)
//   * Poly1305:   RFC 8439 §2.5.2
//   * AEAD ChaCha20-Poly1305: RFC 8439 §2.8.2
//   * TLS PRF:    RFC 6520 / openssl test vector
//   * HKDF:       RFC 5869 Appendix A.1
//   * Rand:       smoke (вызвался без падения, выдал не-нулевые байты)
//
// Любое расхождение возвращает bit в bitmask. crypto_init() требует 0
// (полный PASS), иначе HTTPS выключается.
// ============================================================================
