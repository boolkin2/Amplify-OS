// ============================================================================
// installer.h — графический установщик AMPLIFY-OS (этап 57).
// ============================================================================
#ifndef AOS_X86_64_INSTALLER_H
#define AOS_X86_64_INSTALLER_H

#include <stdbool.h>
#include "multiboot2.h"

// Разобрать cmdline мультибута: токены "installer" / "live" включают
// режим установщика.  Вызывается один раз на раннем этапе загрузки.
void installer_init_from_mb2(const mb2_info_t* info);

// true, если система загружена в live-режиме и должен открыться установщик.
bool installer_should_run(void);

// Полный цикл: 6 экранов + запись на диск.  Возвращает управление, если
// пользователь вышел из установщика в live-сессию.
void installer_run(void);

#endif
