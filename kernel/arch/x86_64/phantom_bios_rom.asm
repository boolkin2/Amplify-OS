; ============================================================================
; phantom_bios_rom.asm — «ПЗУ» BIOS гостя phantom (этап 50.3).
; ----------------------------------------------------------------------------
; Это НЕ код ядра: кусок между phantom_bios_start и phantom_bios_end копируется
; в память гостя по адресу F000:0000 и исполняется там в реальном режиме.
;
; BIOS у нас «паравиртуальный»: сами службы (экран, диск, карта памяти,
; клавиатура, часы) написаны на C и исполняются в гипервизоре
; (phantom_bios.c). В памяти гостя лежат только точки входа: вектор
; прерывания n ведёт на заглушку «VMCALL; IRET». VMCALL — выход в гипервизор;
; тот по адресу заглушки узнаёт номер прерывания, выполняет службу, правит
; регистры гостя и флаги в его стеке — и гость возвращается командой IRET,
; как из настоящего BIOS.
;
; Настоящим кодом гостя сделано только то, что иначе нельзя:
;   INT 08h (таймер) — обязан вызвать INT 1Ch В ГОСТЕ: загрузчики вешают на
;            него свой счётчик времени;
;   INT 16h (клавиатура) — ожидание клавиши должно пропускать прерывания:
;            STI и HLT между попытками (гипервизор сообщает «клавиши ещё нет»
;            флагом переноса и гость засыпает до следующего тика).
; Смещения меток с VMCALL экспортируются: по ним хост отличает эти вызовы.
; ============================================================================

section .rodata

global phantom_bios_start
global phantom_bios_end
global phantom_bios_int08
global phantom_bios_int16
global phantom_bios_int16_call

[bits 16]
phantom_bios_start:

; 256 заглушек по 4 байта: вектор n -> F000:(n*4).
%rep 256
    vmcall
    iret
%endrep

; ---- INT 08h: тик таймера, 18.2 раза в секунду -------------------------------
phantom_bios_int08:
    push ax
    push ds
    xor  ax, ax
    mov  ds, ax
    inc  dword [0x46C]              ; счётчик тиков в области данных BIOS
    int  0x1C                       ; пользовательский крючок таймера
    mov  al, 0x20
    out  0x20, al                   ; конец обслуживания для контроллера 8259
    pop  ds
    pop  ax
    iret

; ---- INT 16h: клавиатура ------------------------------------------------------
; Метки здесь не локальные (без точки): глобальная метка посреди кода
; обрывает область локальных.
phantom_bios_int16:
    sti
phantom_bios_int16_call:
    vmcall                          ; CF=1 — «клавиши нет, подожди и спроси снова»
    jnc  phantom_bios_int16_done
    hlt                             ; до ближайшего прерывания (тик таймера)
    jmp  phantom_bios_int16_call
phantom_bios_int16_done:
    iret

phantom_bios_end:
