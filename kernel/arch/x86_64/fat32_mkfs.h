// ============================================================================
// fat32_mkfs.h — создание файловой системы FAT32 на разделе.
// ----------------------------------------------------------------------------
// Этап 57.  Раньше FAT32-том готовил хост (`mkfs.fat` в scripts/mkdisk-*.sh),
// система умела только читать и писать готовую ФС.  Установщику нужно
// создавать том самостоятельно — на разделе, который он только что разметил.
//
// Модуль самодостаточен: пишет BPB, FSInfo, резервную копию загрузочного
// сектора, обе таблицы FAT и пустой корневой каталог напрямую через disk_io,
// не трогая глобальное состояние драйвера fat32.c.
// ============================================================================
#ifndef AOS_X86_64_FAT32_MKFS_H
#define AOS_X86_64_FAT32_MKFS_H

#include <stdint.h>
#include <stdbool.h>

// Обнуление таблиц FAT на большом разделе занимает секунды, поэтому
// форматирование сообщает о прогрессе (0..100), чтобы UI не выглядел зависшим.
typedef void (*fat32_mkfs_tick_t)(int percent, void* user);

// label — до 11 символов, дополняется пробелами. Возвращает 0 при успехе.
int fat32_mkfs(int dev, uint64_t lba, uint64_t sectors, const char* label,
               fat32_mkfs_tick_t tick, void* user);

#endif
