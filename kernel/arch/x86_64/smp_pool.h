// ============================================================================
// smp_pool.h — пул вычислительных ядер (AP) для тяжёлой математики (этап 49).
// ----------------------------------------------------------------------------
// До этапа 49 Application Processors после старта навсегда засыпали в `hlt`
// с IF=0 — три ядра из четырёх простаивали. Пул превращает их в воркеров:
//
//   * parallel-for — `smp_pool_parallel_for(fn, ctx, n, grain)` режет
//     диапазон [0, n) на куски по grain элементов и раздаёт их свободным AP.
//     Вызывающее ядро тоже работает; возврат — когда все куски посчитаны.
//   * «дирижёр» — `smp_pool_spawn(fn, arg)` запускает ДОЛГУЮ задачу на AP
//     слота 1 (генерация токенов AMPLIFY MIND). Дирижёр сам вызывает
//     parallel-for и раздаёт матричные умножения остальным AP, а BSP в это
//     время спокойно крутит оконный менеджер: UI не подвисает.
//
// Сон и пробуждение: AP загружают общий IDT и спят в `sti; hlt`; BSP/дирижёр
// будят их фиксированным IPI 0xF0. На время генерации включается «горячий»
// режим (smp_pool_hot_begin): воркеры крутятся на `pause` и подхватывают
// задачи без IPI — сотни parallel-for на токен не платят за пробуждение.
//
// Ограничения (осознанные):
//   * код, исполняемый на AP, НЕ должен звать kmalloc/VFS/FAT32/ATA/экран —
//     эти подсистемы однопоточные. Только чистые вычисления над заранее
//     выделенной памятью;
//   * параллельно выполняется одна задача parallel-for; второй вызывающий
//     (если первый ещё не закончил) просто посчитает свой диапазон сам.
// ============================================================================
#ifndef AOS_X86_64_SMP_POOL_H
#define AOS_X86_64_SMP_POOL_H

#include <stdint.h>
#include <stdbool.h>

#define SMP_POOL_WAKE_VECTOR  0xF0
#define SMP_POOL_CONDUCTOR    1        // слот AP, на котором живут долгие задачи

typedef void (*smp_pool_range_fn)(void* ctx, int begin, int end);
typedef void (*smp_pool_task_fn)(void* arg);

// BSP: регистрирует обработчик IPI. Вызывается из smp_init() ДО запуска AP.
void smp_pool_init(void);

// AP: вход в цикл воркера (из ap_main64). Не возвращается.
void smp_pool_ap_entry(int slot) __attribute__((noreturn));

// Число AP, готовых к работе (0 — однопроцессорная машина).
int  smp_pool_workers(void);

// Номер слота текущего ядра (0 = BSP, 1.. = AP).
int  smp_pool_current_slot(void);

// Параллельный цикл по [0, n). Безопасен с любого ядра.
void smp_pool_parallel_for(smp_pool_range_fn fn, void* ctx, int n, int grain);

// «Горячий» режим: воркеры не засыпают между задачами (вложенный счётчик).
void smp_pool_hot_begin(void);
void smp_pool_hot_end(void);

// Долгая задача на ядре-дирижёре. false — нет AP или дирижёр занят.
bool smp_pool_spawn(smp_pool_task_fn fn, void* arg);
bool smp_pool_task_running(void);

// ---- [этап 50] вызов на конкретном ядре и «жилец» ядра -------------------------
// Синхронный вызов fn(arg) на ядре slot (свой слот — прямо здесь). Нужен там,
// где состояние у каждого процессора своё: VMXON/VMXOFF, VMCLEAR.
// false — такого ядра в пуле нет либо это дирижёр, занятый долгой задачей
// (ждать её конца на BSP нельзя: это секунды без кадров).
bool smp_pool_call(int slot, smp_pool_task_fn fn, void* arg);

// «Жилец» — vCPU гостя phantom, привязанный к одному AP и делящий его с пулом.
// Цикл AP зовёт fn(arg), когда у ядра нет работы пула. fn исполняет гостя не
// дольше одного кванта и возвращает:
//     1 — квант отработан, гость готов исполняться дальше;
//     2 — гость готов, но квант не начинал: уступил ядро пулу;
//     0 — гость спит (HLT): ядро свободно для пула и может уснуть;
//   < 0 — жилец закончил, его надо снять.
// Кто кого вытесняет:
//   * пока идёт квант гостя, ядро в parallel-for не участвует (бит в маске
//     гостей) — задачи пула считают остальные ядра и никого не ждут;
//   * в «горячем» режиме (MIND генерирует) после каждого кванта гостя ядро
//     SMP_POOL_HOLD_MS работает на пул: гостю остаётся ~20 % ядра, пулу ~80 %;
//   * вне горячего режима работающий гость получает ядро целиком.
typedef int (*smp_pool_resident_fn)(void* arg);
#define SMP_POOL_HOLD_MS  8

// Какой AP отдать жильцу: старший из готовых, чтобы не делить ядро с дирижёром
// (слот 1), пока есть выбор. 0 — AP нет.
int  smp_pool_pick_resident(void);
bool smp_pool_set_resident(int slot, smp_pool_resident_fn fn, void* arg);
bool smp_pool_resident_active(int slot);
// Разбудить ядро жильца: вывести его из гостя (IPI = VM exit) или из сна.
void smp_pool_kick(int slot);

// Зовёт сам жилец на своём ядре вокруг кванта гостя. enter ставит ядру бит
// «в госте» и возвращает false, если пулу это ядро нужно прямо сейчас (тогда
// в гостя входить нельзя). pending — та же проверка посреди кванта.
bool smp_pool_guest_enter(int slot);
void smp_pool_guest_leave(int slot);
bool smp_pool_pending(int slot);

// [51.3] Разбудить главное ядро (BSP) из сна в цикле WM — прерыванием.
void smp_pool_wake_bsp(void);

// Самопроверка для smoke 49: parallel-for, сверка с последовательным
// результатом, запуск задачи на дирижёре. Печатает в serial.
bool smp_pool_self_test(void);

#endif
