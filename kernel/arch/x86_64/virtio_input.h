// ============================================================================
// virtio_input.h — драйвер virtio-input (подэтап 41.2): клавиатура, планшет
// (абсолютные координаты) и мышь QEMU/Proxmox вместо PS/2.
// ----------------------------------------------------------------------------
// Зачем: PS/2-мышь передаёт только смещения. В консоли Proxmox (VNC) указатель
// хоста и курсор гостя из-за этого расходятся, а 8042 с его буфером в один
// байт теряет пакеты при долгом кадре. virtio-планшет шлёт абсолютные
// координаты через очередь на 64 события и прерывание MSI-X — рассинхрона и
// потерь нет. Устройства в QEMU: `-device virtio-keyboard-pci
// -device virtio-tablet-pci` (в Proxmox — через `args:`). Нет устройств —
// драйвер молчит, работает прежний PS/2-путь.
// ============================================================================
#ifndef AOS_X86_64_VIRTIO_INPUT_H
#define AOS_X86_64_VIRTIO_INPUT_H

#include <stdint.h>
#include <stdbool.h>

// Найти и запустить все устройства virtio-input. Звать после keyboard_init /
// mouse_init и после lapic_init (нужен LAPIC для MSI-X). Возвращает их число.
int  virtio_input_init(void);

// Разобрать накопившиеся события устройств, оставшихся без прерывания.
// Звать при запрещённых прерываниях (см. mouse_poll).
void virtio_input_poll(void);

// Есть ли устройство с абсолютными координатами (планшет).
bool virtio_input_has_tablet(void);
// Сколько событий принято всего (для диагностики и тестов).
uint64_t virtio_input_event_count(void);

#endif
