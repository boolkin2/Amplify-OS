// ============================================================================
// cursor.h — графический курсор для AMPLIFY-OS x86_64.
// ----------------------------------------------------------------------------
// Стандартный 12×19 sprite ARGB (классическая «стрелка» с белой заливкой
// и чёрной обводкой). Hot-spot = (0, 0) (кончик стрелки).
//
// Курсор рисуется в любой gfx_target_t (обычно doublebuf) — и автоматически
// поверх всего остального содержимого. Этап 42 заменит на PNG-спрайт.
// ============================================================================
#ifndef AOS_X86_64_CURSOR_H
#define AOS_X86_64_CURSOR_H

#include "graphics.h"
#include <stdbool.h>

#define CURSOR_W   12
#define CURSOR_H   19

// Нарисовать курсор в указанную точку target. Если tgt == NULL → screen.
void cursor_draw(const gfx_target_t* tgt, int x, int y);

// ----------------------------------------------------------------------------
// [41.2] Курсор «поверх сцены» с сохранением фона (save-under).
// До 41.2 курсор был частью сцены: любое движение мыши означало полную
// перерисовку рабочего стола, окон и полный вывод кадра (12-17 мс под KVM).
// Теперь WM рисует сцену БЕЗ курсора, а курсор кладётся последним через
// cursor_overlay_show: пиксели под ним запоминаются. Сдвиг мыши = вернуть
// старый фон (cursor_overlay_hide), запомнить новый, нарисовать спрайт и
// вывести на экран два маленьких прямоугольника — сцена не трогается.
// Экраны со своим циклом (вход, установщик, FDE) по-прежнему зовут cursor_draw.
// ----------------------------------------------------------------------------
// Спрайт курсора в буфер size x size (ARGB, прозрачный фон) — картинка для
// аппаратного курсора virtio-gpu.
void cursor_render_argb(uint32_t* buf, int size);

void cursor_overlay_show(const gfx_target_t* tgt, int x, int y);
void cursor_overlay_hide(const gfx_target_t* tgt);
// Сцену перерисовали целиком поверх курсора — сохранённый фон больше не нужен.
void cursor_overlay_forget(void);
// Прямоугольник последнего нарисованного курсора; false — курсор не показан.
bool cursor_overlay_rect(int* x, int* y, int* w, int* h);

#endif
