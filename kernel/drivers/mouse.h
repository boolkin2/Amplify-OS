// ============================================================================
// mouse.h - Драйвер мыши (PS/2) для MyOS
// ============================================================================
// Работает через IRQ12 и порты 0x60/0x64 (контроллер клавиатуры 8042)
// Читает 3-байтовые пакеты, обновляет координаты и состояние кнопок.
// ============================================================================

#ifndef MOUSE_H
#define MOUSE_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// Структуры
// ============================================================================

// Состояние мыши
typedef struct {
    int32_t x;          // Координата X на экране
    int32_t y;          // Координата Y на экране
    bool left_btn;      // Левая кнопка нажата
    bool right_btn;     // Правая кнопка нажата
    bool middle_btn;    // Средняя кнопка нажата
} mouse_state_t;

// ============================================================================
// Функции
// ============================================================================

// Инициализация мыши (включение контроллера, IRQ12 и data reporting)
void mouse_init(void);

// Получение текущего состояния мыши
mouse_state_t mouse_get_state(void);

// Получение координаты X
int32_t mouse_get_x(void);

// Получение координаты Y
int32_t mouse_get_y(void);

// Проверка нажатия левой кнопки
bool mouse_is_left_pressed(void);

// Проверка нажатия правой кнопки
bool mouse_is_right_pressed(void);

// Установка координат мыши программно (например, в центр экрана)
void mouse_set_position(int32_t x, int32_t y);

#endif // MOUSE_H
