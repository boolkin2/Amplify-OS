// ============================================================================
// timer.h - Драйвер системного таймера PIT для MyOS
// ============================================================================
// PIT (Programmable Interval Timer) генерирует IRQ0 с заданной частотой
// Используется для отсчёта времени, задержек и многозадачности
// ============================================================================

#ifndef TIMER_H
#define TIMER_H

#include <stdint.h>

// ============================================================================
// Константы PIT
// ============================================================================

// Порты PIT (Intel 8253/8254)
#define PIT_CHANNEL0        0x40    // Канал 0 (системный таймер)
#define PIT_CHANNEL1        0x41    // Канал 1 (не используется)
#define PIT_CHANNEL2        0x42    // Канал 2 (PC Speaker)
#define PIT_COMMAND         0x43    // Командный регистр

// Базовая частота PIT (Hz)
#define PIT_BASE_FREQUENCY  1193182

// Желаемая частота таймера (Hz)
// 100 Hz = 10 ms на тик (хорошо для многозадачности)
#define TIMER_FREQUENCY     100

// Команды PIT
#define PIT_CMD_BINARY      0x00    // Двоичный режим (не BCD)
#define PIT_CMD_MODE2       0x04    // Режим 2: Rate Generator
#define PIT_CMD_MODE3       0x06    // Режим 3: Square Wave
#define PIT_CMD_RW_BOTH     0x30    // Чтение/запись: младший, затем старший байт
#define PIT_CMD_CHANNEL0    0x00    // Канал 0

// Стандартная команда для канала 0
#define PIT_CMD_INIT        (PIT_CMD_CHANNEL0 | PIT_CMD_RW_BOTH | PIT_CMD_MODE2 | PIT_CMD_BINARY)

// ============================================================================
// Функции драйвера таймера
// ============================================================================

// Инициализация таймера
// Настраивает PIT на заданную частоту и регистрирует обработчик IRQ0
void timer_init(void);

// Получение количества тиков с момента загрузки
// Возвращает количество прерываний таймера
uint64_t timer_get_ticks(void);

// Получение времени работы системы в миллисекундах
uint64_t timer_get_uptime_ms(void);

// Получение времени работы системы в секундах
uint32_t timer_get_uptime_sec(void);

// Задержка в миллисекундах (блокирующая)
// Параметры:
//   ms - количество миллисекунд для ожидания
void timer_sleep(uint32_t ms);

// Задержка в тиках таймера (блокирующая)
// Параметры:
//   ticks - количество тиков для ожидания
void timer_wait(uint32_t ticks);

// Получение частоты таймера в Hz
uint32_t timer_get_frequency(void);

#endif // TIMER_H
