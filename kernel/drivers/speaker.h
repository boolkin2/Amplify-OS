// ============================================================================
// speaker.h - Драйвер PC Speaker для MyOS
// ============================================================================
// Использует PIT Channel 2 для генерации звука через системный динамик.
// Порт 0x42 — данные PIT канала 2
// Порт 0x43 — командный регистр PIT
// Порт 0x61 — управление динамиком (биты 0-1)
// ============================================================================

#ifndef SPEAKER_H
#define SPEAKER_H

#include <stdint.h>

// ============================================================================
// Частоты нот (Hz) — 5-я октава
// ============================================================================

#define NOTE_C4     262
#define NOTE_D4     294
#define NOTE_E4     330
#define NOTE_F4     349
#define NOTE_G4     392
#define NOTE_A4     440
#define NOTE_B4     494
#define NOTE_C5     523
#define NOTE_D5     587
#define NOTE_E5     659
#define NOTE_F5     698
#define NOTE_G5     784
#define NOTE_A5     880
#define NOTE_B5     988
#define NOTE_C6     1047

// ============================================================================
// Функции PC Speaker
// ============================================================================

// Включить динамик на заданной частоте (Hz)
void speaker_on(uint32_t frequency);

// Выключить динамик
void speaker_off(void);

// Воспроизвести тон заданной частоты и длительности (мс)
void speaker_beep(uint32_t frequency, uint32_t duration_ms);

// Воспроизвести мелодию загрузки
void speaker_play_boot_melody(void);

#endif // SPEAKER_H
