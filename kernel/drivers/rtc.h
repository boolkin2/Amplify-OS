// ============================================================================
// rtc.h — Real-Time Clock (CMOS) для AMPLIFY-OS
// ============================================================================
// Чтение реального времени и даты из CMOS/RTC по портам 0x70/0x71.
// Используется панелью задач для отображения «настоящего» HH:MM:SS вместо
// uptime, а также приложениями, которым нужна календарная отметка.
// ============================================================================

#ifndef RTC_H
#define RTC_H

#include <stdint.h>

typedef struct {
    uint8_t  second;   // 0..59
    uint8_t  minute;   // 0..59
    uint8_t  hour;     // 0..23
    uint8_t  day;      // 1..31
    uint8_t  month;    // 1..12
    uint16_t year;     // 4-значный (например 2026)
} rtc_time_t;

// Прочитать текущее время из CMOS. Корректно обрабатывает BCD/binary режимы
// и 12/24-часовой формат, ждёт окончания update-цикла RTC, чтобы не получить
// «промежуточное» значение во время инкремента секунд.
void rtc_read(rtc_time_t* out);

#endif // RTC_H
