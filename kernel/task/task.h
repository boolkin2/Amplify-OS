// ============================================================================
// task.h - Многозадачность для MyOS (Этап 18)
// ============================================================================
// Расширена поддержкой загрузки ELF-программ.
// ============================================================================

#ifndef TASK_H
#define TASK_H

#include <stdint.h>
#include "../arch/i386/isr.h"

// ============================================================================
// Константы
// ============================================================================

#define TASK_STACK_SIZE 4096

// ============================================================================
// Схема виртуальной памяти пользовательских процессов (Ring 3)
// ============================================================================
//   0x40000000 - 0x7FFFFFFF  : код и данные приложения (1 GiB)
//   0xA0000000 - 0xBFFFDFFF  : mmap-арена (~512 MiB для анонимной и файловой
//                              памяти через sys_mmap)
//   0xBFFFE000 - 0xBFFFFFFF  : пользовательский стек (одна страница = 4 KiB,
//                              вершина = 0xBFFFF000)
//   0xC0000000 - ...         : зарезервировано под разделяемые библиотеки
// ============================================================================
#define USER_APP_BASE        0x40000000u
#define USER_MMAP_BASE       0xA0000000u
#define USER_STACK_BASE      0xBFFFE000u
#define USER_STACK_TOP       0xBFFFF000u

typedef enum {
    TASK_RUNNING,
    TASK_READY,
    TASK_DEAD
} task_state_t;

// ============================================================================
// Структура задачи (Process Control Block - PCB)
// ============================================================================

// Предварительное объявление: vm_space_t объявлен в kernel/memory/vm.h.
// Используем forward-decl, чтобы избежать циклической зависимости
// (vm.h нужна константа USER_MMAP_BASE из этого файла).
struct vm_space;

// Максимальная длина абсолютного пути для cwd (синхронизируется
// с VFS_MAX_PATH, копируется сюда без include чтобы не тянуть vfs.h).
#define TASK_CWD_MAX        1024

// Максимальная длина «дружественного» имени задачи (для диспетчера задач).
#define TASK_NAME_MAX       31

typedef struct task {
    uint32_t id;                // Уникальный идентификатор задачи
    task_state_t state;         // Текущее состояние
    uint32_t esp;               // Указатель на вершину стека при переключении контекста
    uint32_t stack_base;        // Базовый адрес выделенного стека (для освобождения)
    struct vm_space* vm;        // Адресное пространство (разделяется между потоками процесса)
    char cwd[TASK_CWD_MAX];     // Текущий рабочий каталог (абсолютный путь)
    char name[TASK_NAME_MAX + 1]; // Имя задачи: для kernel-потоков — описательное,
                                  // для user-приложений — путь / имя ELF.
    // Учёт времени для диспетчера задач: сколько таймерных тиков задача
    // была планируемой как RUNNING. Считается в task_switch().
    uint64_t cpu_ticks;
    // Параметры для первого запуска задачи (читаются stub'ом один раз).
    // Хранятся per-task, чтобы разные задачи не гоняли общий глобал.
    uint32_t start_entry;       // user-mode EIP для первого входа в Ring 3
    uint32_t start_stack;       // user-mode ESP
    uint32_t start_arg;         // аргумент для pthread-потока (только SYS_CLONE)
    struct task* next;          // Указатель на следующую задачу в кольцевом списке
} task_t;

// ============================================================================
// Функции
// ============================================================================

// Инициализация системы многозадачности (превращает текущий поток в задачу 0)
void task_init(void);

// Создание новой задачи (потока ядра)
task_t* task_create(void (*entry)(void));

// Завершить текущую задачу
void task_exit_current(void);

// Создание задачи из файла (Ring 3 App — старый формат flat binary)
task_t* task_exec_app(const char* initrd_path);

// Создание задачи из ELF файла (Этап 18)
// Параметры:
//   path — путь к ELF файлу в VFS (напр. "/disk/nexus/bin/hello.elf")
// Возвращает указатель на задачу или NULL при ошибке
task_t* task_exec_elf(const char* path);

// Создание задачи из ELF данных в памяти (Этап 18)
// Параметры:
//   data — указатель на ELF файл в памяти
//   size — размер данных
//   name — имя задачи (для отладки)
// Возвращает указатель на задачу или NULL
task_t* task_exec_elf_memory(const void* data, uint32_t size, const char* name);

// Получение текущей задачи (Этап 18)
task_t* task_get_current(void);

// Доступ к голове кольцевого списка задач (для диспетчера задач).
// Список циклический; обход — `t = head; do { ... ; t = t->next; } while (t != head);`
// Возвращает NULL, если многозадачность ещё не инициализирована.
task_t* task_list_first(void);

// Установить «дружественное» имя задачи. Безопасно вызывать на любом
// этапе после создания структуры task_t. Усекает по TASK_NAME_MAX.
void task_set_name(task_t* t, const char* name);

// Принудительно завершить задачу по id (используется диспетчером задач).
// Возвращает 0 при успехе, -1 если задача не найдена, -2 если попытка
// убить себя (для self-kill используется task_exit_current).
int task_kill_by_id(uint32_t id);

// Создание пользовательского потока в Ring 3 (для SYS_CLONE / pthread_create)
// entry          — адрес функции-потока в user-space
// user_stack_top — верх стека пользователя (память должна быть замаплена вызывающим)
// arg            — аргумент, кладётся на стек перед входом
task_t* task_spawn_user_thread(uint32_t entry, uint32_t user_stack_top, uint32_t arg);

// POSIX fork(): создать дочерний процесс с COW-копией vm родителя.
// Параметры:
//   parent_regs — состояние регистров родителя на момент syscall;
//                 дочерний будет возобновлён c eax=0, родитель получит
//                 pid ребёнка в eax (через regs->eax в вызывающем коде).
// Возвращает task_t* ребёнка или NULL при ошибке.
task_t* task_fork(registers_t* parent_regs);

// POSIX execve(path): заменить адресное пространство и код текущей задачи
// на новый ELF-бинарник. PID сохраняется; старое vm_space освобождается.
// При успехе функция модифицирует `regs` так, что последующий iret из
// syscall-обработчика унесёт управление на entry_point нового ELF в ring3
// с пустым стеком. При ошибке возвращает -1 и ничего не меняет.
// argv/envp пока не поддерживаются (main() без аргументов в MyOS CRT0).
int task_execve(const char* path, registers_t* regs);

// Поиск задачи по id (PID/TID)
task_t* task_find_by_id(uint32_t id);

// Планировщик - переключает контекст на следующую задачу
// Вызывается из таймера. Принимает esp текущей задачи, возвращает esp следующей.
uint32_t task_switch(uint32_t current_esp);

#endif // TASK_H
