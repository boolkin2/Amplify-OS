// ============================================================================
// start.c - CRT0 (C Runtime Startup) для MyOS (Этап 18)
// ============================================================================
// Точка входа для всех пользовательских программ.
// Вызывает main() и передаёт код возврата в sys_exit().
//
// Порядок выполнения:
//   1. Ядро загружает ELF и прыгает на _start
//   2. _start вызывает main()
//   3. Код возврата main() передаётся в myos_exit()
//
// Каждая пользовательская программа должна линковаться с этим файлом.
// ============================================================================

#include "myos.h"

// Прототип main — определяется в пользовательской программе
extern int main(void);

// ============================================================================
// _start — точка входа ELF (вызывается ядром)
// ============================================================================
void _start(void) {
    // Вызываем пользовательскую функцию main()
    int exit_code = main();

    // Завершаем процесс с кодом возврата main
    myos_exit(exit_code);

    // Сюда мы никогда не попадём, но на всякий случай
    while (1) {
        __asm__ volatile("");
    }
}
