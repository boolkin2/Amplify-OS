#!/usr/bin/env bash
# ============================================================================
# pve_run.sh — выполнить локальный скрипт на узле Proxmox.
#   bash scripts/pve_run.sh <файл.sh>
# Скрипт идёт в stdin удалённого `bash -s`: так не страдают кавычки, `$var` и
# скобки (PowerShell и Git Bash портят их в аргументах ssh.exe), а Git Bash
# не переписывает пути, начинающиеся с `/`.
# Код 255 — обрыв шлюза: повторяем. ВНИМАНИЕ: повтор запускает скрипт заново
# с начала, поэтому скрипты держать короткими и идемпотентными, а долгую
# работу запускать на узле через nohup и забирать результат отдельным вызовом.
# ============================================================================
[ -f "$1" ] || { echo "usage: pve_run.sh <script>"; exit 2; }
for i in 1 2 3 4 5; do
    ssh.exe -o BatchMode=yes -o ConnectTimeout=25 pve-node 'bash -s' < "$1"
    rc=$?
    [ $rc -ne 255 ] && exit $rc
    sleep 8
done
exit 255
